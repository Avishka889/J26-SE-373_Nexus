"""apps/web's design system: the tokens and the components every page is built from.

The rule generator wrote each page from raw utility strings, so every app came
out as the same admin form: an input per field, a table per list, one button,
no loading, no empty state, and nothing to say whether a save had worked. The
owner compared the result with what Replit makes of the same prompt, and the
difference was the design system, not the data flow.

So every app ships one: a token set in `styles.css` (light, and dark through
`prefers-color-scheme`, because Tailwind v4 turns each token into a CSS
variable a media query can redefine), and a small component set in `src/ui`:
an app shell, a page header, cards, buttons that say they are working, fields,
a data table with its loading and empty states, and notices. A page written by
the rules and a page improved by a model use the same components, so the two do
not look like two products.

Static on purpose: the same files in every app, holding no word from any
project, so the leakage guard reads nothing into them and a reader can learn
the set once.
"""

