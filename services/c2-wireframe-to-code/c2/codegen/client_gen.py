"""packages/contract: the shared types and the typed client, from the contract.

Generated by rule, never by a model, because this is what makes agreement
checkable: every client method carries a machine readable header line naming
the endpoint it implements, the agreement checker reads those headers back,
and the frontend is constrained to call only these methods. A model writing
this file could quietly invent a method and the whole check would measure
fiction.
"""

from sdlc_contracts import ApiContract, ApiEndpoint, EndpointSchema

from .manifest import FileSet, GeneratedFile
from .naming import camel, client_method_name, pascal, path_params, ts_type

HEADER = "// Generated from the api-contract by the platform. Do not edit by hand."


def _interface(name: str, schema_fields) -> str:
    lines = [f"export interface {pascal(name)} {{"]
    for field in schema_fields:
        optional = "" if field.required else "?"
        lines.append(f"  {camel(field.name)}{optional}: {ts_type(field.type, field.item_ref)};")
    lines.append("}")
    return "\n".join(lines)


def _request_type_name(endpoint: ApiEndpoint) -> str:
    return f"{pascal(endpoint.id)}Request"


def _response_type(endpoint: ApiEndpoint) -> str:
    if endpoint.response is None:
        return "void"
    if endpoint.response.entity:
        entity = pascal(endpoint.response.entity)
        return f"{entity}[]" if _is_collection(endpoint) else entity
    return "unknown"


def _is_collection(endpoint: ApiEndpoint) -> bool:
    return endpoint.method == "GET" and "{" not in endpoint.path


def _request_interface(endpoint: ApiEndpoint) -> str | None:
    schema: EndpointSchema | None = endpoint.request
    if schema is None:
        return None
    if schema.fields:
        return _interface(_request_type_name(endpoint), schema.fields)
    if schema.entity:
        return f'export type {_request_type_name(endpoint)} = Omit<{pascal(schema.entity)}, "id">;'
    return f"export type {_request_type_name(endpoint)} = Record<string, unknown>;"


def generate_types(contract: ApiContract) -> str:
    parts = [HEADER, ""]
    for entity in contract.entities:
        parts.append(_interface(entity.name, entity.fields))
        parts.append("")
    for endpoint in contract.endpoints:
        request = _request_interface(endpoint)
        if request:
            parts.append(request)
            parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def _method_signature(endpoint: ApiEndpoint) -> tuple[str, str, str]:
    """(method name, parameter list, return type)."""
    name = client_method_name(endpoint.id)
    params = [f"{camel(param)}: string" for param in path_params(endpoint.path)]
    if endpoint.request is not None:
        params.append(f"body: {_request_type_name(endpoint)}")
    return name, ", ".join(params), _response_type(endpoint)


def _url_expression(endpoint: ApiEndpoint) -> str:
    url = endpoint.path
    for param in path_params(endpoint.path):
        url = url.replace(f"{{{param}}}", f"${{{camel(param)}}}")
    return f"`${{this.baseUrl}}{url}`"


def generate_client(contract: ApiContract) -> str:
    imports: set[str] = set()
    for entity in contract.entities:
        imports.add(pascal(entity.name))
    for endpoint in contract.endpoints:
        if endpoint.request is not None:
            imports.add(_request_type_name(endpoint))

    lines = [
        HEADER,
        "// The agreement checker reads the `implements` headers below; the",
        "// generated frontend may call these methods and nothing else.",
        "",
        f'import type {{ {", ".join(sorted(imports))} }} from "./types";',
        "",
        "export class ApiClient {",
        "  constructor(private readonly baseUrl: string) {}",
        "",
        "  private async request<T>(method: string, url: string, body?: unknown): Promise<T> {",
        "    const response = await fetch(url, {",
        "      method,",
        '      headers: { "Content-Type": "application/json" },',
        "      body: body === undefined ? undefined : JSON.stringify(body),",
        "    });",
        "    if (!response.ok) {",
        "      throw new Error(`${method} ${url} answered ${response.status}`);",
        "    }",
        "    if (response.status === 204) {",
        "      return undefined as T;",
        "    }",
        "    return (await response.json()) as T;",
        "  }",
    ]

    for endpoint in contract.endpoints:
        name, params, returns = _method_signature(endpoint)
        body_argument = ", body" if endpoint.request is not None else ""
        lines.extend(
            [
                "",
                f"  // implements {endpoint.id} {endpoint.method} {endpoint.path}",
                f"  {name}({params}): Promise<{returns}> {{",
                f'    return this.request<{returns}>("{endpoint.method}", {_url_expression(endpoint)}{body_argument});',
                "  }",
            ]
        )

    lines.append("}")
    return "\n".join(lines) + "\n"


def contract_package(contract: ApiContract, arm_note: str) -> FileSet:
    files = FileSet()
    files.add(
        GeneratedFile(
            path="packages/contract/package.json",
            content=(
                "{\n"
                '  "name": "@app/contract",\n'
                '  "version": "0.1.0",\n'
                '  "private": true,\n'
                '  "type": "module",\n'
                '  "main": "src/index.ts",\n'
                '  "types": "src/index.ts"\n'
                "}\n"
            ),
            stage="frontend-code",
            generator="static",
            summary="The shared contract package manifest.",
        )
    )
    files.add(
        GeneratedFile(
            path="packages/contract/src/types.ts",
            content=generate_types(contract),
            stage="frontend-code",
            generator="rule",
            implements=tuple(entity.name for entity in contract.entities),
            summary="Entity and request types, generated from the contract.",
        )
    )
    files.add(
        GeneratedFile(
            path="packages/contract/src/client.ts",
            content=generate_client(contract),
            stage="frontend-code",
            generator="rule",
            implements=tuple(endpoint.id for endpoint in contract.endpoints),
            summary=f"The typed client, one method per endpoint ({arm_note}).",
        )
    )
    files.add(
        GeneratedFile(
            path="packages/contract/src/index.ts",
            content=f'{HEADER}\nexport * from "./types";\nexport * from "./client";\n',
            stage="frontend-code",
            generator="rule",
            summary="The contract package barrel.",
        )
    )
    return files
