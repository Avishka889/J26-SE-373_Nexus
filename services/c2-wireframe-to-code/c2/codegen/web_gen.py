def _routes(
    wireframes: WireframesArtefact, scope: SprintScope, name: str, plans: dict[str, _ScreenPlan]
) -> str:
    """The routes, inside a shell that makes the screens reachable.

    Without the shell every screen is an island: the links a flow declares only
    go where that flow goes, so a reader who lands on the entry screen can walk
    one path and has no way back. The navigation is the scoped screens grouped
    by their flow, which is the same grouping the wireframes already carry, and
    the shell carries the app's own name.

    A screen about one record takes it in its address, as an optional segment:
    a row or a save opens `/orders/detail/7`, and the navigation's
    `/orders/detail` still reaches the screen, which then asks for one to be
    opened.
    """
    imports = [
        HEADER,
        'import { Routes, Route } from "react-router-dom";',
        'import { AppShell, type NavGroup } from "./ui";',
    ]
    routes = []
    groups: list[tuple[str, list[str]]] = []
    first: str | None = None
    for flow, screen, composite in _scoped_screens(wireframes, scope):
        page = _page_name(flow.id, screen.id)
        imports.append(f'import {{ {page} }} from "./pages/{page}";')
        record = "".join(f"/:{param}?" for param in plans[composite].params)
        routes.append(
            f'        <Route path="/{flow.id}/{screen.id}{record}" element={{<{page} />}} />'
        )
        first = first or page
        if not groups or groups[-1][0] != flow.name:
            groups.append((flow.name, []))
        groups[-1][1].append(
            f'      {{ to: "/{flow.id}/{screen.id}", label: {json.dumps(screen.name)} }},'
        )
    if first is not None:
        routes.insert(0, f'        <Route path="/" element={{<{first} />}} />')
    nav: list[str] = []
    for label, items in groups:
        nav.extend([f"  {{ label: {json.dumps(label)}, items: [", *items, "  ] },"])
    return "\n".join(
        [
            *imports,
            "",
            "const groups: NavGroup[] = [",
            *nav,
            "];",
            "",
            "export function AppRoutes() {",
            "  return (",
            f"    <AppShell name={{{json.dumps(name)}}} groups={{groups}}>",
            "      <Routes>",
            *routes,
            "      </Routes>",
            "    </AppShell>",
            "  );",
            "}",
            "",
        ]
    )


