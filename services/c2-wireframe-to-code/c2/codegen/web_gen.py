HEADER = "// Generated by the platform. Do not edit by hand."


def _t(text: str) -> str:
    """One piece of text, safe to put between JSX tags.

    Screen and block labels come from a language model and are not restricted
    to what JSX reads as text: a single `{` in a label ends the build. Plain
    text stays plain, so the generated source reads as somebody wrote it, and
    anything with JSX punctuation in it becomes a string expression.
    """
    if any(character in text for character in "<>{}"):
        return "{" + json.dumps(text) + "}"
    return text


def _attr(text: str) -> str:
    """The same, for an attribute value.

    A plain quoted attribute where the text allows it, because generated code
    a reader is meant to judge should not look escaped for no reason.
    """
    if '"' in text or "{" in text or "}" in text:
        return "{" + json.dumps(text) + "}"
    return f'"{text}"'


def _column_label(field_name: str) -> str:
    """`container_id` and `placedAt` both read as headings a person wrote.

    The field names arrive in either spelling: the contract's own are snake
    cased and the generated interface camel cases them, and a table heading
    reading `PlacedAt` is the kind of detail that makes generated software look
    generated.
    """
    spaced = field_name.replace("_", " ").replace("-", " ")
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", spaced).strip()
    if not spaced:
        return field_name
    return spaced[:1].upper() + spaced[1:].lower()


def _scoped_screens(wireframes: WireframesArtefact, scope: SprintScope):
    wanted = set(scoped_screen_ids(scope))
    for flow in wireframes.flows:
        for screen in flow.screens:
            composite = f"{flow.id}/{screen.id}"
            if composite in wanted:
                yield flow, screen, composite


def _endpoints_for_screen(
    contract: ApiContract, composite: str
) -> tuple[ApiEndpoint | None, ApiEndpoint | None]:
    """(the read that fills this screen, the write its form submits to).

    The write is chosen rather than taken in contract order. The contract lists
    its endpoints sorted by key, so PATCH came before POST, and a checkout form
    both traced to submitted an update to an order that did not exist yet. A
    screen that shows one record writes to that record when something does; any
    other screen creates when something does.
    """
    read = next(
        (
            endpoint
            for endpoint in contract.endpoints
            if endpoint.method == "GET" and composite in endpoint.traces.screen_ids
        ),
        None,
    )
    writes = [
        endpoint
        for endpoint in contract.endpoints
        if endpoint.method in ("POST", "PATCH", "PUT") and composite in endpoint.traces.screen_ids
    ]
    if not writes:
        return read, None
    record = read.path if read is not None and path_params(read.path) else None

    def fit(endpoint: ApiEndpoint) -> int:
        about_one = bool(path_params(endpoint.path))
        if record is not None:
            if _about(endpoint, record):
                return 0
            return 1 if not about_one else 2
        return 1 if about_one else 0

    return read, min(writes, key=fit)


def _about(endpoint: ApiEndpoint, record_path: str) -> bool:
    """Whether a write is to the record at `record_path`: the record itself or an action on it."""
    return endpoint.path == record_path or endpoint.path.startswith(record_path + "/")


@dataclass(frozen=True)
class _ScreenPlan:
    """What one screen reads and writes, and which record its address names.

    Worked out once for every scoped screen, because three places have to agree
    on it: the route that admits the record's id, the page that reads it, and
    every link and row that leads to the page with one. A page that reached its
    record by a written-in "id" asked the API for `/orders/id` and showed a 404
    on the first record anyone opened.
    """

    read: ApiEndpoint | None
    write: ApiEndpoint | None
    #: The entity its read returns, when it reads one.
    entity: str | None
    #: The record the screen is about, as camel cased route parameters in path
    #: order; empty for a screen about no one record.
    params: tuple[str, ...]


def _screen_plan(contract: ApiContract, screen, composite: str) -> _ScreenPlan:
    read, write = _endpoints_for_screen(contract, composite)
    entity = read.response.entity if read is not None and read.response is not None else None
    fills = read if read is not None and entity else None
    submits = write if write is not None and any(b.kind == "field" for b in screen.blocks) else None
    about = next(
        (
            path_params(endpoint.path)
            for endpoint in (fills, submits)
            if endpoint is not None and path_params(endpoint.path)
        ),
        [],
    )
    return _ScreenPlan(
        read=read, write=write, entity=entity or None, params=tuple(camel(p) for p in about)
    )


def _plans(
    contract: ApiContract, wireframes: WireframesArtefact, scope: SprintScope
) -> dict[str, _ScreenPlan]:
    return {
        composite: _screen_plan(contract, screen, composite)
        for _flow, screen, composite in _scoped_screens(wireframes, scope)
    }


def _record_path(base: str, params: tuple[str, ...]) -> str:
    """A JSX expression for `base` with these route parameters filled in, when all are known.

    Without them the screen's own address, where it asks for a record to be
    opened, rather than an address with `undefined` in it.
    """
    known = " && ".join(params)
    path = base + "".join(f"/${{{param}}}" for param in params)
    return f'{known} ? `{path}` : "{base}"'


def _link_to(flow_id: str, target_id: str, own: tuple[str, ...], plans) -> str:
    """A link's `to` attribute, carrying this screen's record to a screen about the same one.

    An order's detail that links to the order's edit form passes the order on.
    A link from a screen about no record, or about a different one, goes to the
    screen's own address, where it asks for a record to be opened.
    """
    base = f"/{flow_id}/{target_id}"
    target = plans.get(f"{flow_id}/{target_id}")
    if target is None or not target.params or target.params != own:
        return f'"{base}"'
    return "{" + _record_path(base, own) + "}"


def _row_target(flow, screen, plan: _ScreenPlan, plans) -> tuple[str, str] | None:
    """The screen a list's rows open, and what the link in each row says.

    The list's own links first, as the designer drew the way on, then the first
    screen in the flow that shows one record of the listed entity. A row carries
    its own id and nothing else, so only a screen about exactly one record, read
    as the same entity, is somewhere a row can open.
    """

    def opens(target_id: str) -> bool:
        target = plans.get(f"{flow.id}/{target_id}")
        return (
            target is not None
            and target_id != screen.id
            and len(target.params) == 1
            and target.read is not None
            and bool(path_params(target.read.path))
            and target.entity is not None
            and plan.entity is not None
            and pascal(target.entity) == pascal(plan.entity)
        )

    for link in screen.links:
        if opens(link.target_id):
            return link.target_id, link.label
    for other in flow.screens:
        if opens(other.id):
            return other.id, "Open"
    return None


def _entity_columns(contract: ApiContract, entity_name: str | None) -> list[str]:
    """An entity's field names, camel cased to match the generated interface.

    Empty when the contract declares a response entity it never modelled, which
    is a real shape: the page falls back to rendering whole rows rather than
    inventing columns.
    """
    if not entity_name:
        return []
    wanted = pascal(entity_name)
    for entity in contract.entities:
        if pascal(entity.name) == wanted:
            return [camel(field.name) for field in entity.fields]
    return []


def page_flows(wireframes: WireframesArtefact, scope: SprintScope) -> dict[str, object]:
    """Each generated page's path, to the flow it is a screen of.

    The page writer is told what a page is for from its flow's requirements,
    since a screen carries no traces of its own.
    """
    return {
        f"apps/web/src/pages/{_page_name(flow.id, screen.id)}.tsx": flow
        for flow, screen, _composite in _scoped_screens(wireframes, scope)
    }


def _page_name(flow_id: str, screen_id: str) -> str:
    return pascal(f"{flow_id}-{screen_id}-page")


#: A banner's tone, as the Notice component names it. A lookup rather than
#: interpolation, so an unknown tone is a known one.
NOTICE_TONES = {"positive": "positive", "muted": "muted", "neutral": "neutral"}

#: Contract field types a form sends as something other than text.
_NUMERIC = frozenset({"number"})


def _field_types(write: ApiEndpoint | None) -> dict[str, str]:
    """Each request field's contract type, by the camel cased name a page binds."""
    if write is None or write.request is None:
        return {}
    return {camel(field.name): field.type for field in write.request.fields}


def _list_card(
    block, columns: list[str], entity: str, opens: tuple[str, str] | None = None
) -> list[str]:
    """A list block as a card holding a data table of the entity's own fields.

    The identifier is left out when there is anything else to show: it is how
    the app finds a row, not something a person reading the list looks for. When
    a screen shows one of these records, each row links to it with its own id
    (`opens`: that screen's address and the link's words).
    """
    columns = [column for column in columns if column != "id"] or columns
    specs = [
        f"{{ key: {json.dumps(column)}, label: {json.dumps(_column_label(column))}, "
        f"render: (item: {entity}) => cell(item.{column}) }}"
        for column in columns
    ] or [
        f'{{ key: "row", label: {json.dumps(block.label)}, render: (item: {entity}) => cell(item) }}'
    ]
    if opens is not None:
        base, words = opens
        specs.append(
            f'{{ key: "open", label: "", render: (item: {entity}) => '
            f'<Link to={{recordPath("{base}", item)}} className="{ROW_LINK}">{_t(words)}</Link> }}'
        )
    return [
        f"      <Card title={_attr(block.label)} label={_attr(block.label)} flush>",
        "        {failed ? (",
        '          <div className="p-5">',
        '            <Notice tone="danger" title="This list could not be loaded">{failed}</Notice>',
        "          </div>",
        "        ) : (",
        "          <DataTable",
        "            rows={rows}",
        "            loading={loading}",
        "            rowKey={(item, index) => String((item as { id?: string }).id ?? index)}",
        "            columns={[",
        *[f"              {spec}," for spec in specs],
        "            ]}",
        "            empty={",
        "              <EmptyState",
        '                title="Nothing here yet"',
        '                description="This app starts with an empty database."',
        "              />",
        "            }",
        "          />",
        "        )}",
        "      </Card>",
    ]


def _summary_card(block, columns: list[str], chosen: bool = False) -> list[str]:
    """A summary block as a card with the entity's fields as a definition list.

    `chosen`: the record comes from the page's address, so with none there it
    says to open one, rather than that nothing has loaded yet.
    """
    pairs: list[str] = []
    for column in columns:
        pairs.extend(
            [
                "              <div>",
                f'                <dt className="text-muted">{_t(_column_label(column))}</dt>',
                f'                <dd className="mt-0.5 font-medium text-ink">{{cell(row.{column})}}</dd>',
                "              </div>",
            ]
        )
    if not pairs:
        pairs = ['              <dd className="font-medium text-ink">{cell(row)}</dd>']
    return [
        f"      <Card title={_attr(block.label)} label={_attr(block.label)}>",
        "        {loading ? (",
        '          <p className="flex items-center gap-2 text-sm text-muted">',
        '            <Spinner label="Loading" />',
        "            Loading",
        "          </p>",
        "        ) : failed ? (",
        '          <Notice tone="danger" title="This could not be loaded">{failed}</Notice>',
        "        ) : row === null ? (",
        (
            '          <p className="text-sm text-muted">Nothing is open here yet: open one to see '
            "it here.</p>"
            if chosen
            else '          <p className="text-sm text-muted">Nothing loaded yet.</p>'
        ),
        "        ) : (",
        '          <dl className="grid grid-cols-1 gap-x-6 gap-y-4 text-sm sm:grid-cols-2">',
        *pairs,
        "          </dl>",
        "        )}",
        "      </Card>",
    ]


def _form_card(fields, screen, has_write: bool, types: dict[str, str]) -> list[str]:
    """Every field block of a screen in one card, with the submit that saves them."""
    lines = [
        "      <Card>",
        '        <div className="grid gap-4 sm:grid-cols-2">',
    ]
    for block in fields:
        name = camel(block.label)
        kind = ' type="number"' if types.get(name) in _NUMERIC else ""
        lines.append(
            f"          <Field label={_attr(block.label)}{kind} value={{{name}}} "
            f"onChange={{set{pascal(block.label)}}} />"
        )
    lines.append("        </div>")
    if has_write:
        submit_label = next(
            (link.label for link in screen.links if link.variant == "primary"), "Save"
        )
        lines.extend(
            [
                '        <div className="mt-5 flex justify-end">',
                f"          <Button onClick={{submit}} busy={{saving}}>{_t(submit_label)}</Button>",
                "        </div>",
            ]
        )
    lines.append("      </Card>")
    return lines


def _page_body(
    flow, screen, composite: str, contract: ApiContract, plans: dict[str, _ScreenPlan]
) -> str:
    plan = plans[composite]
    read, write = plan.read, plan.write
    fields = [block for block in screen.blocks if block.kind == "field"]
    name = _page_name(flow.id, screen.id)
    # The record this screen is about, named by its address: the route admits
    # it (`_routes`) and the page reads it here, so it is never a written-in id.
    own = plan.params

    is_collection = read is not None and "{" not in read.path
    entity_name = plan.entity
    entity = pascal(entity_name) if entity_name else None
    columns = _entity_columns(contract, entity_name)
    reads = read is not None and entity is not None
    lists = reads and is_collection and any(block.kind == "list" for block in screen.blocks)
    writes = write is not None and bool(fields)
    types = _field_types(write)
    # The primary link is where a saved form goes next: the checkout's "Place
    # order" is both the save and the way to the confirmation. Saving then
    # moves there, and the link is not offered a second time beside the button.
    primary = next((link for link in screen.links if link.variant == "primary"), None)
    moves = writes and primary is not None and primary.target_id != screen.id
    links = [link for link in screen.links if not (moves and link is primary)]
    # A screen that is used rather than filled in: its keys enter their values
    # into the first field, and its display reads that field out. With no field
    # the page keeps an entry of its own for them.
    keys = [block for block in screen.blocks if block.kind == "button"]
    shows = any(block.kind == "display" for block in screen.blocks)
    entering = any(block.link_id is None for block in keys)
    own_entry = not fields and (entering or (shows and bool(keys)))
    entry = camel(fields[0].label) if fields else ("entry" if own_entry else None)
    key_links = {link.id: link for link in screen.links}
    # A link a key carries is not offered a second time under the keys.
    carried = {block.link_id for block in keys if block.link_id}
    links = [link for link in links if link.id not in carried]
    rows_open = _row_target(flow, screen, plan, plans) if lists else None
    # Each row carries that link with its own record, so the list's bare one,
    # which could only open the screen asking for a record, is not offered too.
    if rows_open is not None:
        links = [link for link in links if link.target_id != rows_open[0]]

    # What the write is told about its record: this screen's own, when the
    # write is to that record or the record came from the write; nothing for a
    # create; and, for a write about some other record, nothing it can know.
    write_params: tuple[str, ...] = ()
    write_blind = False
    if writes and path_params(write.path):
        record = read.path if reads and not is_collection else None
        if record is None or _about(write, record):
            write_params = own
        else:
            write_blind = True
    # Where a save moves on to: the created record, when the next screen shows
    # one and the create answered with it; this screen's record, when the next
    # screen is about the same one; otherwise the next screen's own address.
    moves_to = ""
    if moves and primary is not None:
        base = f"/{flow.id}/{primary.target_id}"
        target = plans.get(f"{flow.id}/{primary.target_id}")
        created = (
            not path_params(write.path)
            and write.response is not None
            and bool(write.response.entity)
        )
        if target is not None and target.params and target.params == own:
            moves_to = "`" + base + "".join(f"/${{{param}}}" for param in own) + "`"
        elif target is not None and len(target.params) == 1 and created:
            moves_to = f'recordPath("{base}", created)'
        else:
            moves_to = f'"{base}"'

    headers = [HEADER, f"// screen: {composite} ({screen.name})"]
    for endpoint in (read, write):
        if endpoint is not None:
            headers.append(f"// implements {endpoint.id} {endpoint.method} {endpoint.path}")

    # Only what the page uses, so a reader deciding whether to trust generated
    # code is not asked to account for an import nothing reads.
    hooks = [
        hook
        for hook, used in (("useEffect", reads), ("useState", reads or bool(fields) or own_entry))
        if used
    ]
    ui = {"PageHeader"}
    if reads and is_collection:
        ui |= {"Card", "DataTable", "EmptyState", "Notice"}
    if reads and not is_collection:
        ui |= {"Card", "Notice", "Spinner"}
    if fields:
        ui |= {"Card", "Field"}
    if writes:
        ui |= {"Button", "Notice"}
    if any(block.kind == "banner" for block in screen.blocks):
        ui.add("Notice")
    if any(block.link_id is None for block in keys):
        ui.add("Button")
    linked_keys = any(block.link_id in key_links for block in keys)

    imports = []
    if hooks:
        imports.append(f'import {{ {", ".join(hooks)} }} from "react";')
    router = [
        name
        for name, used in (
            ("Link", bool(links) or linked_keys or rows_open is not None),
            ("useNavigate", moves and not write_blind),
            ("useParams", bool(own)),
        )
        if used
    ]
    if router:
        imports.append(f'import {{ {", ".join(router)} }} from "react-router-dom";')
    if entity:
        imports.append(f'import type {{ {entity} }} from "@app/contract";')
    if reads or writes:
        imports.append('import { client } from "../api";')
    formats = [
        name
        for name, used in (
            ("cell", reads),
            ("recordPath", rows_open is not None or moves_to.startswith("recordPath(")),
        )
        if used
    ]
    if formats:
        imports.append(f'import {{ {", ".join(formats)} }} from "../format";')
    imports.append(f'import {{ {", ".join(sorted(ui))} }} from "../ui";')

    body: list[str] = []
    if own:
        body.append(f"  const {{ {', '.join(own)} }} = useParams();")
    missing = " || ".join(f"!{param}" for param in own)
    if reads and is_collection:
        body.extend(
            [
                f"  const [rows, setRows] = useState<{entity}[]>([]);",
                "  const [loading, setLoading] = useState(true);",
                '  const [failed, setFailed] = useState("");',
                "  const load = () => {",
                "    setLoading(true);",
                f"    client.{client_method_name(read.id)}()",
                "      .then((found) => {",
                "        setRows(found);",
                '        setFailed("");',
                "      })",
                "      .catch((error: unknown) => setFailed(error instanceof Error ? error.message : String(error)))",
                "      .finally(() => setLoading(false));",
                "  };",
                "  useEffect(load, []);",
            ]
        )
    elif reads:
        body.extend(
            [
                f"  const [row, setRow] = useState<{entity} | null>(null);",
                "  const [loading, setLoading] = useState(true);",
                '  const [failed, setFailed] = useState("");',
                "  useEffect(() => {",
                # With no record in the address there is nothing to ask for, and
                # the card says to open one instead of asking for `undefined`.
                f"    if ({missing}) {{",
                "      setLoading(false);",
                "      return;",
                "    }",
                f"    client.{client_method_name(read.id)}({', '.join(own)})",
                "      .then(setRow)",
                "      .catch((error: unknown) => setFailed(error instanceof Error ? error.message : String(error)))",
                "      .finally(() => setLoading(false));",
                f"  }}, [{', '.join(own)}]);",
            ]
        )

    if own_entry:
        body.append('  const [entry, setEntry] = useState("");')
    # Every field block is a controlled input, wired write or not: the JSX
    # below binds state for each one, so each one must exist.
    for block in fields:
        body.append(f'  const [{camel(block.label)}, set{pascal(block.label)}] = useState("");')
    if writes:
        submit_arguments = list(write_params)
        if write.request is not None:
            sent = ", ".join(
                f"{camel(block.label)}: Number({camel(block.label)})"
                if types.get(camel(block.label)) in _NUMERIC
                else camel(block.label)
                for block in fields
            )
            submit_arguments.append(f"{{ {sent} }} as never")
        if moves and primary is not None:
            done = [f"        navigate({moves_to});"]
        else:
            done = [
                '        setResult({ ok: true, text: "Saved." });',
                *[f'        set{pascal(block.label)}("");' for block in fields],
                *(["        load();"] if lists else []),
            ]
        if write_blind:
            # A write about a record this screen does not name: it cannot know
            # which one, and saying so beats sending a made-up id.
            guard = [
                "    setResult({",
                "      ok: false,",
                '      text: "This screen does not say which record this would change, so nothing was sent.",',
                "    });",
                "    return;",
            ]
            call = []
        else:
            guard = (
                [
                    f"    if ({' || '.join(f'!{param}' for param in write_params)}) {{",
                    '      setResult({ ok: false, text: "Open one first: there is nothing here to save to." });',
                    "      return;",
                    "    }",
                ]
                if write_params
                else []
            )
            then = "(created) =>" if moves_to.startswith("recordPath(") else "() =>"
            call = [
                "    setSaving(true);",
                "    setResult(null);",
                f"    client.{client_method_name(write.id)}({', '.join(submit_arguments)})",
                f"      .then({then} {{",
                *done,
                "      })",
                "      .catch((error: unknown) =>",
                "        setResult({ ok: false, text: error instanceof Error ? error.message : String(error) }),",
                "      )",
                "      .finally(() => setSaving(false));",
            ]
        body.extend(
            [
                *(["  const navigate = useNavigate();"] if moves and not write_blind else []),
                "  const [saving, setSaving] = useState(false);",
                "  const [result, setResult] = useState<{ ok: boolean; text: string } | null>(null);",
                "  const submit = () => {",
                *guard,
                *call,
                "  };",
            ]
        )

    description = f" description={_attr(' / '.join(screen.crumbs))}" if screen.crumbs else ""
    jsx: list[str] = [
        '    <div className="mx-auto w-full max-w-4xl space-y-6">',
        f"      <PageHeader title={_attr(screen.name)}{description} />",
    ]
    if writes:
        jsx.extend(
            [
                "      {result &&",
                "        (result.ok ? (",
                '          <Notice tone="positive" title="Saved" />',
                "        ) : (",
                '          <Notice tone="danger" title="That did not go through">',
                "            {result.text}",
                "          </Notice>",
                "        ))}",
            ]
        )

    def to(target_id: str) -> str:
        return _link_to(flow.id, target_id, own, plans)

    form_written = False
    blocks = list(screen.blocks)
    index = 0
    while index < len(blocks):
        block = blocks[index]
        index += 1
        if block.kind == "button":
            run = [block]
            while index < len(blocks) and blocks[index].kind == "button":
                run.append(blocks[index])
                index += 1
            jsx.extend(_key_grid(run, entry, key_links, to))
            continue
        if block.kind == "display":
            jsx.extend(_display(block, entry))
            continue
        if block.kind == "list" and reads and is_collection:
            opens = (f"/{flow.id}/{rows_open[0]}", rows_open[1]) if rows_open is not None else None
            jsx.extend(_list_card(block, columns, entity or "unknown", opens))
        elif block.kind == "field":
            if not form_written:
                jsx.extend(_form_card(fields, screen, writes, types))
                form_written = True
        elif block.kind == "summary" and reads and not is_collection:
            jsx.extend(_summary_card(block, columns, chosen=bool(own)))
        elif block.kind == "banner":
            tone = NOTICE_TONES.get(block.tone or "neutral", "neutral")
            jsx.append(
                f'      <Notice tone="{tone}" title={_attr(block.label)}>'
                + (_t(block.value) if block.value else "")
                + "</Notice>"
            )
        elif block.kind == "row":
            jsx.extend(
                [
                    '      <div className="flex items-baseline justify-between gap-4 rounded-panel '
                    'border border-line bg-surface px-4 py-3 shadow-panel">',
                    f'        <span className="text-sm text-ink">{_t(block.label)}</span>',
                    *(
                        [f'        <span className="text-sm text-muted">{_t(block.value)}</span>']
                        if block.value
                        else []
                    ),
                    "      </div>",
                ]
            )
        else:
            jsx.append(
                f'      <p className="text-sm text-muted">{_t(block.value or block.label)}</p>'
            )

    if links:
        jsx.append(
            '      <nav aria-label="Next" className="flex flex-wrap gap-2 border-t border-line pt-5">'
        )
        for link in links:
            style = LINK_PRIMARY if link.variant == "primary" else LINK_SECONDARY
            jsx.append(
                f'        <Link to={to(link.target_id)} className="{style}">{_t(link.label)}</Link>'
            )
        jsx.append("      </nav>")
    jsx.append("    </div>")

    return (
        "\n".join(
            [
                *headers,
                *imports,
                "",
                f"export function {name}() {{",
                *body,
                "  return (",
                *jsx,
                "  );",
                "}",
            ]
        )
        + "\n"
    )


#: A key that leads somewhere, drawn like the keys beside it.
KEY_LINK = (
    "inline-flex h-12 items-center justify-center rounded-control border border-line-strong "
    "bg-surface text-base font-medium text-ink transition-colors hover:bg-surface-2"
)


def _key_grid(run, entry: str | None, links: dict, to) -> list[str]:
    """Consecutive buttons as a grid of keys.

    A key with a link goes where that link goes. Any other key enters its value
    into the screen's entry, and a value of "" clears it: a calculator's digits,
    its operators and its "C" are all that, and nothing here pretends to know
    what "=" should compute. The page writer is where a key does more.
    """
    lines = ['      <div className="grid grid-cols-4 gap-2">']
    for block in run:
        link = links.get(block.link_id) if block.link_id else None
        if link is not None:
            lines.append(
                f'        <Link to={to(link.target_id)} className="{KEY_LINK}">'
                f"{_t(block.label)}</Link>"
            )
            continue
        value = block.value if block.value is not None else block.label
        if entry is None:
            action = "undefined"
        elif value == "":
            action = f'() => set{entry[:1].upper()}{entry[1:]}("")'
        else:
            action = f"() => set{entry[:1].upper()}{entry[1:]}({entry} + {json.dumps(value)})"
        lines.append(
            f'        <Button variant="secondary" className="h-12 text-base" onClick={{{action}}}>'
            f"{_t(block.label)}</Button>"
        )
    lines.append("      </div>")
    return lines


def _display(block, entry: str | None) -> list[str]:
    """A large read-out: of the screen's entry, or of its own value on a screen with none."""
    shown = f"{{{entry} || {json.dumps(block.value or '0')}}}" if entry else _t(block.value or "")
    return [
        '      <div className="rounded-panel border border-line bg-surface-2 px-5 py-4 text-right">',
        '        <p className="text-xs font-medium uppercase tracking-wide text-muted">'
        f"{_t(block.label)}</p>",
        '        <p aria-live="polite" className="mt-1 truncate font-mono text-3xl font-semibold '
        f'tabular-nums text-ink">{shown}</p>',
        "      </div>",
    ]


