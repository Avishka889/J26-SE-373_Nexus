"""apps/web: routes from flows, navigation from links, pages from screens.

The rule generated page bodies are complete and functional, not stubs: a list
block fetches through the client method whose endpoint traces to this screen
and renders the rows as a table of the entity's own fields; a form renders its
fields and submits through the traced write endpoint. The optional model fill
may replace a page body with a richer one, under the constraint that it calls
only client methods that exist and keeps its `implements` headers; when the
model misbehaves or is absent, these bodies are what ships, and the build must
pass on them alone.

Styling is Tailwind v4, configured in CSS rather than a config file, with one
small token set in `@theme` that both authors share. It is here because an app
with no styling reads as a mock: the walk produced fifteen working endpoints
and a page of unstyled `JSON.stringify`, and a reader cannot tell those two
facts apart by looking. The tokens are the shared vocabulary, so a page written
by rule and a page improved by a model do not look like two different products.
"""

