def _routes_test(
    wireframes: WireframesArtefact, scope: SprintScope, plans: dict[str, _ScreenPlan]
) -> str:
    """Each route renders its screen; a screen about one record asks for the one its address names.

    The second case is what the first could not see: a detail page that asked
    the API for `/orders/id` rendered its heading as well as one that asked for
    the record it was opened on.
    """
    cases = []
    for flow, screen, composite in _scoped_screens(wireframes, scope):
        cases.append(
            f'  it("renders {screen.name}", async () => {{\n'
            f'    render(<MemoryRouter initialEntries={{["/{flow.id}/{screen.id}"]}}><AppRoutes /></MemoryRouter>);\n'
            f'    expect(await screen_.findByRole("heading", {{ name: "{screen.name}", level: 1 }})).toBeTruthy();\n'
            "  });"
        )
        plan = plans[composite]
        fetches = (
            plan.params
            and plan.read is not None
            and plan.entity
            and bool(path_params(plan.read.path))
        )
        if fetches:
            values = [str(41 + index) for index, _ in enumerate(plan.params)]
            address = f"/{flow.id}/{screen.id}/" + "/".join(values)
            expected = " && ".join(f'asked("{value}")' for value in values)
            cases.append(
                f'  it("opens {screen.name} for the record its address names", async () => {{\n'
                f'    render(<MemoryRouter initialEntries={{["{address}"]}}><AppRoutes /></MemoryRouter>);\n'
                f'    expect(await screen_.findByRole("heading", {{ name: "{screen.name}", level: 1 }})).toBeTruthy();\n'
                f"    await waitFor(() => expect({expected}).toBe(true));\n"
                "  });"
            )
    return "\n".join(
        [
            HEADER,
            'import { afterEach, describe, expect, it, vi } from "vitest";',
            'import { cleanup, render, screen as screen_, waitFor } from "@testing-library/react";',
            'import { MemoryRouter } from "react-router-dom";',
            'import { AppRoutes } from "../routes";',
            "",
            "// The pages fetch on mount; the routes test is about routing, so the",
            "// network is stubbed to an empty, well formed answer.",
            "const network = vi.fn(async (_url: RequestInfo | URL, _init?: RequestInit) =>",
            '  new Response("[]", { status: 200 }),',
            ");",
            'vi.stubGlobal("fetch", network);',
            "// Each case renders on its own: a screen rendered twice would find two headings.",
            "afterEach(cleanup);",
            "// Whether any request so far named this path segment, such as a record's id.",
            "const asked = (segment: string) =>",
            '  network.mock.calls.some(([url]) => String(url).split("/").includes(segment));',
            "",
            'describe("the generated routes", () => {',
            *cases,
            "});",
            "",
        ]
    )
