"""One monorepo per generated project: apps/web, apps/api, packages/contract.

The CI workflow the repo carries runs install, typecheck and tests only.
Deploy authority stays with the platform, and no platform token ever lands in
the generated repository's secrets.
"""

from sdlc_contracts import ApiContract, SprintScope, WireframesArtefact

from .api_gen import api_app
from .client_gen import contract_package
from .manifest import FileSet, GeneratedFile
from .web_gen import web_app

