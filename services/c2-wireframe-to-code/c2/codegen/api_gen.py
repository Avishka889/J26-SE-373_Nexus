"""apps/api: entity models, repositories, and routes from the contract.

The rule generated handler bodies are complete CRUD against a repository
interface, and every entity has two repositories behind it: one in memory, and
one on MongoDB through the official driver. `app.ts` takes MongoDB when
MONGODB_URL names a database and memory when nothing does, which is what the
tests, the build sandbox and a preview run against, since none of them has a
database; the tests are held to memory whatever the shell exports, and the
server says as it starts which one keeps its records. The optional model fill
may enrich a handler body under the constraint that it keeps to the repository
interface; the rule bodies are what ships when it does not.

This docstring once said a Mongoose repository was generated beside the one in
memory and wired by environment. None was, so every released app kept its
records in memory and lost them on each restart and each release.
"""

import json

from sdlc_contracts import ApiContract, ApiEndpoint, EntityModel, SchemaField

from .manifest import FileSet, GeneratedFile
from .naming import camel, express_path, pascal, path_params, ts_type

HEADER = "// Generated by the platform. Do not edit by hand."


def _resource_of_path(path: str) -> str:
    return path.strip("/").split("/", 1)[0]


def _entity_for_resource(contract: ApiContract, resource: str) -> EntityModel | None:
    from ..contract.vocab import resource_of

    for entity in contract.entities:
        if resource_of(entity.name) == resource:
            return entity
    return None


def _model_file(entity: EntityModel) -> str:
    name = pascal(entity.name)
    field_lines = []
    for field in entity.fields:
        optional = "" if field.required else "?"
        field_lines.append(
            f"  {camel(field.name)}{optional}: {ts_type(field.type, field.item_ref)};"
        )
    return "\n".join(
        [
            HEADER,
            f"// entity: {entity.name} (traces {', '.join(entity.traces) or 'none'})",
            'import { randomUUID } from "node:crypto";',
            'import type { Collection, WithId } from "mongodb";',
            "",
            f"export interface {name} {{",
            *field_lines,
            "}",
            "",
            f"export interface {name}Repository {{",
            f"  list(): Promise<{name}[]>;",
            f"  get(id: string): Promise<{name} | undefined>;",
            f'  create(item: Omit<{name}, "id">): Promise<{name}>;',
            f"  update(id: string, patch: Partial<{name}>): Promise<{name} | undefined>;",
            "  remove(id: string): Promise<boolean>;",
            "}",
            "",
            "// The sandbox and the generated tests run against this. No database",
            "// is required to prove the contract shape; the build report says so.",
            f"export class InMemory{name}Repository implements {name}Repository {{",
            f"  private items = new Map<string, {name}>();",
            "  private sequence = 0;",
            "",
            f"  async list(): Promise<{name}[]> {{",
            "    return [...this.items.values()];",
            "  }",
            f"  async get(id: string): Promise<{name} | undefined> {{",
            "    return this.items.get(id);",
            "  }",
            f'  async create(item: Omit<{name}, "id">): Promise<{name}> {{',
            "    this.sequence += 1;",
            "    const id = String(this.sequence);",
            f"    const created = {{ ...item, id }} as {name};",
            "    this.items.set(id, created);",
            "    return created;",
            "  }",
            f"  async update(id: string, patch: Partial<{name}>): Promise<{name} | undefined> {{",
            "    const existing = this.items.get(id);",
            "    if (!existing) return undefined;",
            "    const updated = { ...existing, ...patch, id };",
            "    this.items.set(id, updated);",
            "    return updated;",
            "  }",
            "  async remove(id: string): Promise<boolean> {",
            "    return this.items.delete(id);",
            "  }",
            "}",
            "",
            *_mongo_repository(name),
        ]
    )


def _mongo_repository(name: str) -> list[str]:
    """The repository on MongoDB, as the app runs it when MONGODB_URL names a database.

    Written for node's type stripping, which runs the backend: the collection
    is a declared field assigned in the constructor, because a parameter
    property is TypeScript that has to be compiled, and the driver's types come
    in through `import type`, which stripping erases. Ids are strings the app
    makes and are kept as the document's own `_id`, so an id reads the same in
    memory and in the database, and no ObjectId reaches a URL.
    """
    return [
        f"/** The {name} document MongoDB keeps: its id is the document's own `_id`. */",
        f'export type {name}Document = Omit<{name}, "id"> & {{ _id: string }};',
        "",
        f"function from{name}Document({{ _id, ...fields }}: WithId<{name}Document>): {name} {{",
        f"  return {{ ...fields, id: _id }} as {name};",
        "}",
        "",
        "// Kept in MongoDB when the app is given a database (MONGODB_URL).",
        f"export class Mongo{name}Repository implements {name}Repository {{",
        f"  private readonly collection: Collection<{name}Document>;",
        "",
        f"  constructor(collection: Collection<{name}Document>) {{",
        "    this.collection = collection;",
        "  }",
        "",
        f"  async list(): Promise<{name}[]> {{",
        f"    return (await this.collection.find().toArray()).map(from{name}Document);",
        "  }",
        f"  async get(id: string): Promise<{name} | undefined> {{",
        "    const found = await this.collection.findOne({ _id: id });",
        f"    return found ? from{name}Document(found) : undefined;",
        "  }",
        f'  async create(item: Omit<{name}, "id">): Promise<{name}> {{',
        "    const id = randomUUID();",
        "    await this.collection.insertOne({ ...item, _id: id });",
        f"    return {{ ...item, id }} as {name};",
        "  }",
        f"  async update(id: string, patch: Partial<{name}>): Promise<{name} | undefined> {{",
        "    // The id is the document's own and never changes, whatever the patch says;",
        "    // and MongoDB refuses an empty $set, where memory answers with the record.",
        f"    const {{ id: _ignored, ...fields }} = patch as Partial<{name}> & {{ id?: unknown }};",
        "    if (Object.keys(fields).length === 0) return this.get(id);",
        "    const updated = await this.collection.findOneAndUpdate(",
        "      { _id: id },",
        "      { $set: fields },",
        '      { returnDocument: "after" },',
        "    );",
        f"    return updated ? from{name}Document(updated) : undefined;",
        "  }",
        "  async remove(id: string): Promise<boolean> {",
        "    return (await this.collection.deleteOne({ _id: id })).deletedCount === 1;",
        "  }",
        "}",
        "",
    ]


#: The line a handler carries when it answers an action without doing it. The
#: agreement check reports every one, so the review sees which actions do nothing.
ACKNOWLEDGED_ONLY = "acknowledged only, nothing generated for what it does:"


def _handler(endpoint: ApiEndpoint, entity: EntityModel | None) -> list[str]:
    """A complete handler body against the repository. Never a stub."""
    params = path_params(endpoint.path)
    id_expr = f"req.params.{camel(params[0])}" if params else ""
    lines: list[str] = []
    if len(params) > 1:
        # Said out loud rather than silently dropped: the repository interface
        # is keyed by one id, so a nested parameter reaches the handler and
        # this generated body does not use it. A model fill may; the manifest
        # records which generator wrote the body either way.
        unused = ", ".join(f"req.params.{camel(name)}" for name in params[1:])
        lines.append(f"    // not used by this generated body: {unused}")
    if endpoint.validation:
        for rule in endpoint.validation:
            lines.append(f"    // validation: {rule}")
    writes = endpoint.method in ("PATCH", "PUT") or (endpoint.method == "POST" and not params)
    if writes:
        request = endpoint.request
        fields = request.fields if request and request.fields else entity.fields if entity else []
        lines.extend(_bound_checks(fields))
    if endpoint.method == "GET" and not params:
        lines.append("    res.json(await repository.list());")
    elif endpoint.method == "GET":
        lines.extend(
            [
                f"    const found = await repository.get({id_expr});",
                "    if (!found) {",
                '      res.status(404).json({ error: "not found" });',
                "      return;",
                "    }",
                "    res.json(found);",
            ]
        )
    elif endpoint.method == "POST" and not params:
        lines.append("    res.status(201).json(await repository.create(req.body));")
    elif endpoint.method in ("PATCH", "PUT"):
        lines.extend(
            [
                f"    const updated = await repository.update({id_expr}, req.body);",
                "    if (!updated) {",
                '      res.status(404).json({ error: "not found" });',
                "      return;",
                "    }",
                "    res.json(updated);",
            ]
        )
    elif endpoint.method == "DELETE":
        lines.extend(
            [
                f"    const removed = await repository.remove({id_expr});",
                "    if (!removed) {",
                '      res.status(404).json({ error: "not found" });',
                "      return;",
                "    }",
                "    res.status(204).end();",
            ]
        )
    else:
        # A POST subaction (`/carts/{id}/fill`). The contract names the verb,
        # and nothing in the design says what it does to the record, so the
        # handler acknowledges it and changes nothing. It says so in a line the
        # agreement check reads, rather than answering as though it had been
        # done (`validate/agreement.py`).
        lines.extend(
            [
                f"    // {ACKNOWLEDGED_ONLY} {endpoint.method} {endpoint.path}",
                f"    const found = await repository.get({id_expr});",
                "    if (!found) {",
                '      res.status(404).json({ error: "not found" });',
                "      return;",
                "    }",
                "    res.json(found);",
            ]
        )
    return lines


def _bound_checks(fields: list[SchemaField]) -> list[str]:
    """A 400 for a value outside the bounds the contract states, before anything is kept.

    The bounds were words in a comment, and the handler kept any value: the
    Movie Tracker took release years 1999 and 2027 where its criteria said 2000
    to 2026. Only a value given is checked, so an update that leaves a field
    out leaves it alone.
    """
    lines: list[str] = []
    for field in fields:
        name = camel(field.name)
        value = f"req.body.{name}"
        for holds, says in _bounds_of(field, value, name):
            lines.extend(
                [
                    f"    if (req.body?.{name} !== undefined && !({holds})) {{",
                    f'      res.status(400).json({{ error: "{says}" }});',
                    "      return;",
                    "    }",
                ]
            )
    return lines


def _bounds_of(field: SchemaField, value: str, name: str) -> list[tuple[str, str]]:
    """Each bound of a field as the condition that holds inside it, and the words."""
    checks: list[tuple[str, str]] = []
    if field.minimum is not None or field.maximum is not None:
        holds = [f'typeof {value} === "number"']
        if field.minimum is not None:
            holds.append(f"{value} >= {_number(field.minimum)}")
        if field.maximum is not None:
            holds.append(f"{value} <= {_number(field.maximum)}")
        checks.append((" && ".join(holds), _range_words(name, field.minimum, field.maximum, "")))
    if field.min_length is not None or field.max_length is not None:
        holds = [f'typeof {value} === "string"']
        if field.min_length is not None:
            holds.append(f"{value}.length >= {field.min_length}")
        if field.max_length is not None:
            holds.append(f"{value}.length <= {field.max_length}")
        checks.append(
            (
                " && ".join(holds),
                _range_words(name, field.min_length, field.max_length, " characters"),
            )
        )
    if field.one_of:
        choices = json.dumps(list(field.one_of), separators=(",", ":"))
        checks.append(
            (f"{choices}.includes({value})", f"{name} must be one of {', '.join(field.one_of)}")
        )
    return checks


def _range_words(name: str, low: float | None, high: float | None, unit: str) -> str:
    """A bound in the words the 400 answers with: "between 2000 and 2026", "at most 9"."""
    if low is not None and high is not None:
        if unit:
            return f"{name} must be {_number(low)} to {_number(high)}{unit}"
        return f"{name} must be between {_number(low)} and {_number(high)}"
    if low is not None:
        return f"{name} must be at least {_number(low)}{unit}"
    return f"{name} must be at most {_number(high)}{unit}"  # type: ignore[arg-type]


def _number(value: float) -> str:
    """A bound as written in code and in words: 2000, not 2000.0."""
    return str(int(value)) if float(value).is_integer() else str(value)


def _sample_for(field: SchemaField) -> str:
    """A seed value for one field, inside the bounds the contract states.

    The type's seed when it is inside them: a test that sent 1 for a release year
    the handler bounds to 2000 to 2026 would be refused for a reason it is not
    testing.
    """
    if field.one_of:
        return json.dumps(field.one_of[0])
    if field.type == "number" and (field.minimum is not None or field.maximum is not None):
        seed = 1.0
        if field.minimum is not None and seed < field.minimum:
            seed = float(field.minimum)
        if field.maximum is not None and seed > field.maximum:
            seed = float(field.maximum)
        return _number(seed)
    if field.type == "string" and (field.min_length is not None or field.max_length is not None):
        seed = "sample"
        if field.max_length is not None and len(seed) > field.max_length:
            seed = "s" * field.max_length
        if field.min_length is not None and len(seed) < field.min_length:
            seed = "s" * field.min_length
        return json.dumps(seed)
    return SAMPLE_VALUES.get(field.type, '"sample"')


def _registration_order(endpoints: list[ApiEndpoint]) -> list[ApiEndpoint]:
    """Literal segments before parameterised ones, at every depth.

    Express matches in registration order, so `router.get("/:id")` registered
    first swallows `/today`: the literal path reaches the id handler, which
    looks up a route called "today", finds none, and answers 404. The contract
    declared both and the code served one.

    Sorting by how many path parameters a route has puts every literal path in
    front of every path that could shadow it, which is the whole of the fix at
    this shape. The rule arm never emits a literal sub path, so nothing caught
    this until the LLM arm produced `GET /routes/today` on the first live walk.
    """
    return sorted(endpoints, key=lambda e: (len(path_params(e.path)), e.path))


def _routes_file(contract: ApiContract, resource: str, endpoints: list[ApiEndpoint]) -> str:
    entity = _entity_for_resource(contract, resource)
    entity_name = pascal(entity.name) if entity else None
    lines = [
        HEADER,
        f"// resource: /{resource}",
        'import { Router } from "express";',
    ]
    if entity_name:
        lines.append(
            f'import {{ type {entity_name}Repository }} from "../models/{entity_name}.ts";'
        )
    repo_type = f"{entity_name}Repository" if entity_name else "unknown"
    lines.extend(
        [
            "",
            f"export function {camel(resource)}Router(repository: {repo_type}): Router {{",
            "  const router = Router();",
        ]
    )
    for endpoint in _registration_order(endpoints):
        method = endpoint.method.lower()
        lines.extend(
            [
                "",
                f"  // implements {endpoint.id} {endpoint.method} {endpoint.path}",
                f"  // auth: {', '.join(endpoint.auth_actors) or 'unauthenticated'}",
                f'  router.{method}("{express_path(endpoint.path.removeprefix("/" + resource)) or "/"}", async (req, res) => {{',
                *_handler(endpoint, entity),
                "  });",
            ]
        )
    lines.extend(["", "  return router;", "}", ""])
    return "\n".join(lines)


#: Where the records are kept, said once in the app it describes.
_STORAGE = """/**
 * Where the records are kept: the database MONGODB_URL names, or this process's
 * memory when nothing does (the tests, the build sandbox, a preview), which a
 * restart empties. `storage` says which, and the server says it as it starts.
 * A database that does not answer fails its requests within five seconds
 * rather than holding them open.
 */
const databaseUrl = process.env.MONGODB_URL?.trim();
const database = databaseUrl
  ? new MongoClient(databaseUrl, { serverSelectionTimeoutMS: 5000 }).db()
  : undefined;
export const storage: "mongodb" | "memory" = database ? "mongodb" : "memory";"""


def _app_file(resources: list[str], contract: ApiContract) -> str:
    lines = [HEADER, 'import express from "express";', 'import { MongoClient } from "mongodb";']
    constructions = []
    mounts = []
    for resource in resources:
        entity = _entity_for_resource(contract, resource)
        if entity is None:
            continue
        entity_name = pascal(entity.name)
        router_name = f"{camel(resource)}Router"
        lines.append(f'import {{ {router_name} }} from "./routes/{resource}.ts";')
        lines.append(
            f"import {{ InMemory{entity_name}Repository, Mongo{entity_name}Repository, "
            f'type {entity_name}Document }} from "./models/{entity_name}.ts";'
        )
        constructions.append(
            f"export const {camel(resource)}Repository = database\n"
            f"  ? new Mongo{entity_name}Repository("
            f'database.collection<{entity_name}Document>("{resource}"))\n'
            f"  : new InMemory{entity_name}Repository();"
        )
        mounts.append(f'app.use("/{resource}", {router_name}({camel(resource)}Repository));')
    return "\n".join(
        [
            *lines,
            "",
            _STORAGE,
            "",
            "export const app = express();",
            "app.use(express.json());",
            "",
            *constructions,
            *mounts,
            "",
        ]
    )


