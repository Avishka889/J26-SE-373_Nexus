#: A seed value per field type, typed the way `ts_type` types the field.
#:
#: Every `FieldType` the contract allows appears here, and a test asserts the
#: two tables cover the same set. They came apart once: only number and boolean
#: were mapped and everything else fell back to a string, so the first contract
#: that carried an `array` field generated `tags: "sample"` against a
#: `unknown[]` model and the whole typecheck step failed. The rule arm never
#: emits array or object, so nothing caught it until the LLM arm did, on the
#: first live walk.
