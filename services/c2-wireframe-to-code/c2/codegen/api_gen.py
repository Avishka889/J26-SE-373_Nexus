#: What a nested path parameter becomes in a generated test URL.
NESTED_PLACEHOLDER = "1"


def _test_url(endpoint: ApiEndpoint) -> tuple[str, bool]:
    """The URL a contract test calls, and whether it is a nested route.

    The first path parameter is the seeded row's id, because the route file is
    about that resource and the test creates one. Any parameter after it names
    something this generator cannot create: nothing in the contract says how a
    stop comes to exist on a route, so it becomes a literal.

    Substituting `${created.<name>}` for every parameter, which is what this
    did, produced `${created.stop_id}` against a `Route` and failed the whole
    typecheck. The rule arm only ever emits one parameter, so nothing caught it
    until the LLM arm emitted `PATCH /routes/{id}/stops/{stop_id}`.
    """
    params = path_params(endpoint.path)
    url = endpoint.path
    for index, param in enumerate(params):
        url = url.replace(f"{{{param}}}", "${created.id}" if index == 0 else NESTED_PLACEHOLDER)
    return url, len(params) > 1


def _tests_file(resource: str, endpoints: list[ApiEndpoint], entity: EntityModel | None) -> str:
    entity_fields = {camel(f.name): f for f in (entity.fields if entity else [])}
    sample_pairs = []
    for field_name, field in entity_fields.items():
        if field_name == "id":
            continue
        sample_pairs.append(f"{field_name}: {_sample_for(field)}")
    sample = "{ " + ", ".join(sample_pairs) + " }" if sample_pairs else "{}"

    cases = []
    seeds = False
    for endpoint in endpoints:
        path, nested = _test_url(endpoint)
        method = endpoint.method.lower()
        if endpoint.method == "POST" and not path_params(endpoint.path):
            cases.append(
                f'  it("implements {endpoint.id}", async () => {{\n'
                f'    const answer = await request(app).post("{endpoint.path}").send({sample});\n'
                "    expect(answer.status).toBe(201);\n"
                "    expect(answer.body.id).toBeTruthy();\n"
                "  });"
            )
        elif endpoint.method == "GET" and not path_params(endpoint.path):
            cases.append(
                f'  it("implements {endpoint.id}", async () => {{\n'
                f'    const answer = await request(app).get("{endpoint.path}");\n'
                "    expect(answer.status).toBe(200);\n"
                "    expect(Array.isArray(answer.body)).toBe(true);\n"
                "  });"
            )
        else:
            # Seed through the repository, not through a create route: the
            # contract may well have no create endpoint for this entity, and
            # each test exercises exactly one endpoint.
            body = f".send({sample})" if endpoint.method in ("PATCH", "PUT") else ""
            seeds = True
            # A nested route names a resource this generator cannot create:
            # nothing in the contract says how a stop comes to exist on a
            # route. The test still proves the route is registered, reachable
            # and does not fall over, and says so instead of asserting a
            # lookup it never set up.
            accepted = "[200, 204, 404]" if nested else "[200, 204]"
            note = (
                "\n    // The nested id is a placeholder: the contract does not say how to\n"
                "    // create one, so a 404 is a correct answer here and a 500 is not.\n"
                if nested
                else "\n"
            )
            cases.append(
                f'  it("implements {endpoint.id}", async () => {{{note}'
                f"    const created = await {camel(resource)}Repository.create({sample});\n"
                f"    const answer = await request(app).{method}(`{path}`){body};\n"
                f"    expect({accepted}).toContain(answer.status);\n"
                "  });"
            )
    return "\n".join(
        [
            HEADER,
            "// One test per endpoint: the route answers, in the contract's shape.",
            'import { describe, expect, it } from "vitest";',
            'import request from "supertest";',
            f'import {{ app{f", {camel(resource)}Repository" if seeds else ""} }} from "../app.ts";',
            "",
            f'describe("/{resource} implements its contract", () => {{',
            *cases,
            "});",
            "",
        ]
    )


def api_app(contract: ApiContract) -> FileSet:
    files = FileSet()
    for path, content in _STATIC.items():
        files.add(
            GeneratedFile(
                path=path,
                content=content,
                stage="backend-code",
                generator="static",
                summary="Api scaffold.",
            )
        )
    for entity in contract.entities:
        files.add(
            GeneratedFile(
                path=f"apps/api/src/models/{pascal(entity.name)}.ts",
                content=_model_file(entity),
                stage="backend-code",
                generator="rule",
                implements=(entity.name,),
                summary=f"The {entity.name} model and repositories.",
            )
        )

    by_resource: dict[str, list[ApiEndpoint]] = {}
    for endpoint in contract.endpoints:
        by_resource.setdefault(_resource_of_path(endpoint.path), []).append(endpoint)

    for resource, endpoints in sorted(by_resource.items()):
        entity = _entity_for_resource(contract, resource)
        files.add(
            GeneratedFile(
                path=f"apps/api/src/routes/{resource}.ts",
                content=_routes_file(contract, resource, endpoints),
                stage="backend-code",
                generator="rule",
                implements=tuple(endpoint.id for endpoint in endpoints),
                summary=f"The /{resource} routes.",
            )
        )
        files.add(
            GeneratedFile(
                path=f"apps/api/src/__tests__/{resource}.contract.test.ts",
                content=_tests_file(resource, endpoints, entity),
                stage="backend-code",
                generator="rule",
                implements=tuple(endpoint.id for endpoint in endpoints),
                summary=f"Per endpoint contract tests for /{resource}.",
            )
        )

    files.add(
        GeneratedFile(
            path="apps/api/src/app.ts",
            content=_app_file(sorted(by_resource), contract),
            stage="backend-code",
            generator="rule",
            implements=tuple(sorted(by_resource)),
            summary="Mounts every generated router.",
        )
    )
    return files
