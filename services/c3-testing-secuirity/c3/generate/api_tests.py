"""API tests from the OpenAPI export, under a three tier oracle.

The generated repository already ships one test per endpoint, written by C2:
it sends a request and asserts the status is in an accepted set. That is a
smoke test, and it is what these are measured against. What this adds is an
oracle with tiers, each of which can fail on its own and say something
different:

1. **Status class.** The operation answers the code the document declares, not
   merely something in a permissive set.
2. **Schema conformance.** The response body carries every required field of
   the declared response schema, with the declared type. A route that answers
   200 with the wrong shape passes tier one and fails here.
3. **Declared invariants.** The rules the contract states in words: a request
   missing a required field is refused, a caller who is not an allowed actor is
   refused.

Tier three is where this component stops writing tests and starts writing
findings, and the distinction is the honest half of the design. A test asserts
behaviour that should exist and might; when the generated application has no
authentication at all, no test can assert a refusal, and asserting one would
produce a red suite that says "this test failed" where the true statement is
"this feature was never built". Those become gaps on the report instead.

Everything here derives from the exported document rather than from the
contract object, so the export is load bearing rather than decorative: a test
generated from it names the operation by `operationId` and the story by
`x-traces`, exactly as a consumer of the document would.
"""

import json
from dataclasses import dataclass, field
from typing import Any

from sdlc_contracts import EndpointSchema, EntityModel, SchemaField

from ..harness.report import case_id
from .samples import as_literal, incomplete_body, out_of_bounds, sample_body, sample_value

HEADER = (
    "// Generated by the platform's testing component from the API contract's\n"
    "// OpenAPI export. Three tiers: the status the document declares, the\n"
    "// shape it declares, and the rules it states in words.\n"
    "//\n"
    "// Do not edit by hand: a regeneration replaces this file.\n"
)

#: How a declared field type shows up in JavaScript at runtime. `date` and `id`
#: are strings on the wire, which is what a test can check; asserting they are
#: well formed dates is a tier three rule and belongs with the invariants.
_TYPEOF = {
    "string": "string",
    "number": "number",
    "boolean": "boolean",
    "date": "string",
    "id": "string",
    "object": "object",
    "array": "object",
}


@dataclass(frozen=True)
class GeneratedCase:
    """One test this component wrote, so the report can list it before it runs.

    The generation stage writes a report whose cases are all `not-run`, which
    is the literal truth: the tests exist and have not been executed. That
    report is built from these.
    """

    suite_path: str
    id: str
    name: str
    kind: str = "api"
    origin: str = "skeleton"
    endpoint_ids: list[str] = field(default_factory=list)
    story_id: str | None = None
    criterion_id: str = ""
    requirement_ids: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class Gap:
    """A contract obligation no test can assert, and why.

    Not a failing test. The generated application has no authentication, so a
    test asserting a refusal would fail forever and would say the wrong thing:
    the fault is an absent feature, not a broken one. Carried on the report and
    turned into a remediation proposal later.
    """

    endpoint_id: str
    kind: str
    detail: str


@dataclass
class ApiSuite:
    files: dict[str, str] = field(default_factory=dict)
    cases: list[GeneratedCase] = field(default_factory=list)
    gaps: list[Gap] = field(default_factory=list)


def resource_of(path: str) -> str:
    """The first path segment, which is what the app mounts a router on."""
    return path.strip("/").split("/")[0] or "root"


def _describe(resource: str) -> str:
    """The `describe` the oracle file opens with, and half of every case id.

    Written once because it is written twice: into the file, where the runner
    reads it, and into the declared case id, where the report does. The two
    disagreed by two characters and no declared case ever matched the case it
    became.
    """
    return f"/{resource} answers what the contract declares"


def _required_fields(schema: dict[str, Any], document: dict[str, Any]) -> list[tuple[str, str]]:
    """The required properties of a response schema, as name and typeof.

    Follows one `$ref` into the document's components, because that is how the
    export names an entity, and reads an array's items rather than the array.
    """
    resolved = _resolve(schema, document)
    if resolved.get("type") == "array":
        resolved = _resolve(resolved.get("items") or {}, document)
    properties = resolved.get("properties") or {}
    required = resolved.get("required") or []
    pairs: list[tuple[str, str]] = []
    for name in required:
        declared = (properties.get(name) or {}).get("type", "string")
        pairs.append((name, _TYPEOF.get(str(declared), "string")))
    return pairs


def _resolve(schema: dict[str, Any], document: dict[str, Any]) -> dict[str, Any]:
    reference = schema.get("$ref")
    if not isinstance(reference, str) or not reference.startswith("#/components/schemas/"):
        return schema
    name = reference.rsplit("/", 1)[-1]
    return ((document.get("components") or {}).get("schemas") or {}).get(name) or {}


def _success_code(operation: dict[str, Any]) -> str:
    for code in sorted(operation.get("responses") or {}):
        if code.startswith("2"):
            return code
    return "200"


def _is_collection(path: str) -> bool:
    return "{" not in path


#: What an id that does not exist gets, whatever else the contract declares.
#:
#: The first version of this read the first 4xx in the document and asserted
#: 401 on an endpoint declaring both, which is the same mistake it was written
#: to fix, one status along: the request is well formed, the generated
#: application has no authentication at all, and it answers 404 because the
#: thing is missing. What the contract wishes for is a gap on the report, not
#: an assertion in a test.
NOT_FOUND = "404"


def _creator_for(path: str, document: dict[str, Any]) -> dict[str, Any] | None:
    """The POST on this path's collection, if the contract has one.

    An item route needs something to address. Creating through the API rather
    than through the application's repository is deliberate: it exercises the
    public surface, and it keeps this generator from having to know how the
    code generator names its internals.
    """
    collection = "/" + resource_of(path)
    return ((document.get("paths") or {}).get(collection) or {}).get("post")


def _path_expression(path: str, created: bool) -> str:
    """The URL a test requests, as a TypeScript template literal.

    A path parameter becomes the id of the thing the test just created, or a
    placeholder when it could not create one.
    """
    parts: list[str] = []
    first = True
    for segment in path.strip("/").split("/"):
        if segment.startswith("{") and segment.endswith("}"):
            parts.append("${id}" if first and created else "does-not-exist")
            first = False
        else:
            parts.append(segment)
    return "/" + "/".join(parts)


def build(
    document: dict[str, Any],
    *,
    entities: dict[str, EntityModel],
    request_schemas: dict[str, EndpointSchema | None],
) -> ApiSuite:
    """One test file per resource, plus the gaps no test can cover.

    `request_schemas` comes from the contract rather than the document because
    a sample body is built from declared field types, and the document has
    already flattened those into JSON Schema. Same source, read where it is
    easiest to read correctly.
    """
    suite = ApiSuite()
    by_resource: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, operations in (document.get("paths") or {}).items():
        for method, operation in operations.items():
            by_resource.setdefault(resource_of(path), []).append((path, method, operation))

    for resource, operations in sorted(by_resource.items()):
        path_name = f"apps/api/src/__tests__/{resource}.oracle.test.ts"
        blocks: list[str] = []
        for path, method, operation in sorted(operations, key=lambda row: (row[0], row[1])):
            blocks.extend(
                _operation_tests(
                    suite,
                    document,
                    path=path,
                    method=method,
                    operation=operation,
                    suite_path=path_name,
                    entities=entities,
                    request_schema=request_schemas.get(operation.get("operationId", "")),
                )
            )
        if not blocks:
            continue
        suite.files[path_name] = "\n".join(
            [
                HEADER,
                'import { describe, expect, it } from "vitest";',
                'import request from "supertest";',
                'import { app } from "../app.ts";',
                "",
                f"describe({json.dumps(_describe(resource))}, () => {{",
                *blocks,
                "});",
                "",
            ]
        )
    return suite


def _operation_tests(
    suite: ApiSuite,
    document: dict[str, Any],
    *,
    path: str,
    method: str,
    operation: dict[str, Any],
    suite_path: str,
    entities: dict[str, EntityModel],
    request_schema: EndpointSchema | None,
) -> list[str]:
    endpoint_id = str(operation.get("operationId") or f"{method}-{path}")
    traces = operation.get("x-traces") or {}
    story_ids = list(traces.get("storyIds") or [])
    requirement_ids = list(traces.get("requirementIds") or [])
    code = _success_code(operation)
    body = sample_body(request_schema, entities)
    sends = f".send({as_literal(body)})" if body else ""

    creator = None if _is_collection(path) else _creator_for(path, document)
    created = creator is not None
    setup: list[str] = []
    if created:
        collection = "/" + resource_of(path)
        setup = [
            "    // Addressed through the API rather than through the app's own",
            "    // internals, so this test exercises the public surface only.",
            f'    const seeded = await request(app).post("{collection}")'
            f"{_creator_send(document, collection)};",
            "    const id = seeded.body?.id;",
            '    expect(id, "the collection POST should answer with the created id")'
            ".toBeDefined();",
        ]

    url = _path_expression(path, created)
    blocks: list[str] = []

    # An item route the contract gives no way to create cannot be asked for its
    # success status: the id in the URL is one this test invented, and the
    # application is right to refuse it. The first live run of this generator
    # asserted 200 against `/calculation-inputs/does-not-exist`, got the 404 the
    # handler correctly returns, and reported six failures that were all the
    # test's fault. A component whose claim is honesty must not ship tests that
    # fail for the wrong reason: those failures reach the healing loop next, and
    # it would try to classify a generator bug as brittleness.
    #
    # So the test asserts what it can actually establish, and the success path
    # becomes a gap on the report rather than a red line in the suite.
    unreachable = not _is_collection(path) and not created
    if unreachable:
        code = NOT_FOUND
        suite.gaps.append(
            Gap(
                endpoint_id=endpoint_id,
                kind="no-way-to-create",
                detail=(
                    f"the contract declares {method.upper()} {path} but no POST on "
                    f"/{resource_of(path)} that would create something to address, so no "
                    f"test can reach its {_success_code(operation)}. What is asserted "
                    "instead is the refusal of an id that does not exist."
                ),
            )
        )

    # ---- tier one: the status the document declares
    name = (
        f"{endpoint_id} answers {code} for an id that does not exist"
        if unreachable
        else f"{endpoint_id} answers {code}"
    )
    blocks.append(
        "\n".join(
            [
                f'  it("{name}", async () => {{',
                *setup,
                f"    const answer = await request(app).{method}(`{url}`){sends};",
                f"    expect(answer.status).toBe({code});",
                "  });",
                "",
            ]
        )
    )
    suite.cases.append(
        GeneratedCase(
            suite_path=suite_path,
            id=case_id(suite_path, _describe(resource_of(path)), name),
            name=name,
            endpoint_ids=[endpoint_id],
            story_id=story_ids[0] if story_ids else None,
            requirement_ids=requirement_ids,
        )
    )

    # ---- tier two: the shape the document declares
    #
    # Only when tier one reached the success response. Checking a success schema
    # against a not found body asserts that `{ error: "not found" }` has an id,
    # which is the second half of the same wrong failure.
    success = {} if unreachable else (operation.get("responses") or {}).get(code) or {}
    schema = ((success.get("content") or {}).get("application/json") or {}).get("schema") or {}
    required = _required_fields(schema, document)
    if required:
        collection_shaped = _resolve(schema, document).get("type") == "array"
        name = f"{endpoint_id} answers the declared shape"
        assertions: list[str] = []
        if collection_shaped:
            assertions.append("    expect(Array.isArray(answer.body)).toBe(true);")
            assertions.append("    const item = answer.body[0];")
            assertions.append("    if (item !== undefined) {")
            for field_name, kind in required:
                assertions.append(f'      expect(item).toHaveProperty("{field_name}");')
                assertions.append(f'      expect(typeof item["{field_name}"]).toBe("{kind}");')
            assertions.append("    }")
        else:
            for field_name, kind in required:
                assertions.append(f'    expect(answer.body).toHaveProperty("{field_name}");')
                assertions.append(f'    expect(typeof answer.body["{field_name}"]).toBe("{kind}");')
        blocks.append(
            "\n".join(
                [
                    f'  it("{name}", async () => {{',
                    *setup,
                    f"    const answer = await request(app).{method}(`{url}`){sends};",
                    *assertions,
                    "  });",
                    "",
                ]
            )
        )
        suite.cases.append(
            GeneratedCase(
                suite_path=suite_path,
                id=case_id(suite_path, _describe(resource_of(path)), name),
                name=name,
                endpoint_ids=[endpoint_id],
                story_id=story_ids[0] if story_ids else None,
                requirement_ids=requirement_ids,
            )
        )

    # ---- tier three: the rules the document states in words
    missing = incomplete_body(request_schema, entities)
    if missing is not None:
        _, dropped = missing
        suite.gaps.append(
            Gap(
                endpoint_id=endpoint_id,
                kind="validation-not-enforced",
                detail=(
                    f"the contract requires {dropped} and the generated handler does not "
                    "check it, so a request without it is accepted. No test asserts the "
                    "refusal, because the check was never written: this is an absent "
                    "feature rather than a broken one."
                ),
            )
        )
    # ---- tier three: the bounds the contract states. The generated handler
    # refuses a value outside them before it keeps anything, so the refusal is a
    # feature that exists and is asserted, where a check nothing wrote is a gap.
    writes = method in ("patch", "put") or (method == "post" and _is_collection(path))
    if writes and not unreachable and request_schema is not None:
        for bounded in _bounded_fields(request_schema, entities):
            for value, why in out_of_bounds(bounded):
                name = (
                    f"{endpoint_id} refuses {bounded.name} {as_literal(value)}, {why}"
                    if bounded.type == "number"
                    else f"{endpoint_id} refuses a {bounded.name} {why}"
                )
                refused = as_literal({**body, bounded.name: value})
                blocks.append(
                    "\n".join(
                        [
                            f'  it("{name}", async () => {{',
                            *setup,
                            f"    const answer = await request(app).{method}(`{url}`)"
                            f".send({refused});",
                            "    expect(answer.status).toBe(400);",
                            "  });",
                            "",
                        ]
                    )
                )
                suite.cases.append(
                    GeneratedCase(
                        suite_path=suite_path,
                        id=case_id(suite_path, _describe(resource_of(path)), name),
                        name=name,
                        endpoint_ids=[endpoint_id],
                        story_id=story_ids[0] if story_ids else None,
                        requirement_ids=requirement_ids,
                    )
                )
    if operation.get("x-auth-actors"):
        actors = ", ".join(str(actor) for actor in operation["x-auth-actors"])
        suite.gaps.append(
            Gap(
                endpoint_id=endpoint_id,
                kind="auth-not-implemented",
                detail=(
                    f"the contract restricts this to {actors} and the generated "
                    "application has no authentication at all, so no test can assert a "
                    "refusal."
                ),
            )
        )
    return blocks


def _creator_send(document: dict[str, Any], collection: str) -> str:
    """What the setup POST sends.

    Built from the collection's own request schema in the document, so the
    creation is as likely to succeed as the contract allows. Read out of the
    document rather than out of the contract because the operation being set up
    is not the one under test, and the document is what names it.
    """
    post = ((document.get("paths") or {}).get(collection) or {}).get("post") or {}
    schema = (
        ((post.get("requestBody") or {}).get("content") or {}).get("application/json") or {}
    ).get("schema") or {}
    resolved = _resolve(schema, document)
    properties = resolved.get("properties") or {}
    required = resolved.get("required") or []
    fields = [_field_from(name, properties.get(name) or {}) for name in required]
    if not fields:
        return ""
    body = {f.name: _sample_for(f) for f in fields}
    return f".send({as_literal(body)})"


def _field_from(name: str, schema: dict[str, Any]) -> SchemaField:
    """A required field as the document states it, its bounds included, so a sample
    of it stays inside them."""
    kind = _field_type(schema)
    numeric = kind == "number"
    textual = kind == "string"
    return SchemaField(
        name=name,
        type=kind,  # type: ignore[arg-type]
        required=True,
        minimum=schema.get("minimum") if numeric else None,
        maximum=schema.get("maximum") if numeric else None,
        min_length=schema.get("minLength") if textual else None,
        max_length=schema.get("maxLength") if textual else None,
        one_of=[str(value) for value in schema.get("enum") or []] if textual else [],
    )


def _bounded_fields(schema: EndpointSchema, entities: dict[str, EntityModel]) -> list[SchemaField]:
    """The fields a request carries that the contract bounds, through its entity
    when the request names one instead of spelling its fields."""
    entity = entities.get(schema.entity)
    fields = schema.fields or (entity.fields if entity is not None else [])
    return [
        field
        for field in fields
        if field.name != "id"
        and (
            field.minimum is not None
            or field.maximum is not None
            or field.min_length is not None
            or field.max_length is not None
            or field.one_of
        )
    ]


def _field_type(schema: dict[str, Any]) -> str:
    declared = str(schema.get("type") or "string")
    return declared if declared in _TYPEOF else "string"


def _sample_for(schema_field: SchemaField) -> Any:
    return sample_value(schema_field, {})
