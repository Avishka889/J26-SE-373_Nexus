class TestEveryTestGetsAFreshApplication:
    """What Book Tracker's release was refused over, as a fill could undo it.

    The generated app builds its store when `app.ts` loads, and a static import
    loads it once for the whole file, so "given a user with one book already in
    their list" found the book the test before it had added: three books, not
    two, and staging refused the candidate. The skeleton now loads the app
    afresh before every test; these are the ways an answer could put the
    sharing back.
    """

    NAMES: ClassVar[list[str]] = ["app", "booksRepository"]
    SETUP = fresh_app_block(["app", "booksRepository"])
    SKELETON = (
        "// story: US-1 Add a book\n// requirements: R-1\n"
        'import { beforeEach, describe, it, vi } from "vitest";\n\n'
        + SETUP
        + '\ndescribe("Add a book", () => {\n'
        '  it.todo("US-1 AC-1-1: given no books, when one is added, then the list holds it");\n'
        "});\n"
    )
    FILLED = (
        "// story: US-1 Add a book\n// requirements: R-1\n"
        'import { beforeEach, describe, expect, it, vi } from "vitest";\n'
        'import request from "supertest";\n\n' + SETUP + '\ndescribe("Add a book", () => {\n'
        '  it("US-1 AC-1-1: given no books, when one is added, then the list holds it", '
        "async () => {\n"
        '    await request(app).post("/books").send({ title: "Dune" });\n'
        '    const listed = await request(app).get("/books");\n'
        "    expect(listed.body).toHaveLength(1);\n"
        "  });\n"
        "});\n"
    )

    def _problems(self, filled: str) -> list[str]:
        return static_problems(self.SKELETON, filled)

    def test_a_fill_that_keeps_the_setup_is_accepted(self) -> None:
        """Its dynamic import and its type queries are the setup's own, not a
        body reaching past the skeleton."""
        assert self._problems(self.FILLED) == []

    def test_dropping_the_setup_for_a_static_import_is_refused(self) -> None:
        shared = self.FILLED.replace(self.SETUP, 'import { app } from "../app.ts";\n')

        problems = self._problems(shared)

        assert any("loads the application afresh before every test" in one for one in problems)
        assert any("../app.ts is imported directly" in one for one in problems)

    def test_importing_the_app_beside_the_setup_is_refused(self) -> None:
        both = self.FILLED.replace(
            'import request from "supertest";\n',
            'import request from "supertest";\nimport { app as shared } from "../app.ts";\n',
        )

        assert any("../app.ts is imported directly" in one for one in self._problems(both))

    def test_a_type_imported_from_the_app_shares_nothing(self) -> None:
        typed = self.FILLED.replace(
            'import request from "supertest";\n',
            'import request from "supertest";\nimport type { Book } from "../app.ts";\n',
        )

        assert self._problems(typed) == []

    def test_a_reindented_setup_is_still_the_setup(self) -> None:
        moved = self.FILLED.replace("  vi.resetModules();", "      vi.resetModules();")

        assert self._problems(moved) == []

    def test_a_dynamic_import_in_a_body_is_still_refused(self) -> None:
        reaching = self.FILLED.replace(
            "    expect(listed.body).toHaveLength(1);",
            '    const again = await import("../app.ts");\n'
            "    expect(listed.body).toHaveLength(1);",
        )

        assert any("imports a module at run time" in one for one in self._problems(reaching))

    def test_the_prompt_offers_the_bound_names_and_not_the_module(self, tmp_path) -> None:
        app = tmp_path / "apps" / "api" / "src"
        (app / "__tests__").mkdir(parents=True)
        (app / "app.ts").write_text("export const app = 1;\nexport const booksRepository = 2;\n")
        repo = TargetRepo(root=tmp_path, kind="generated", stack="node", apps=("apps/api",))

        context = context_for(
            _story(),
            ApiContract(version=1),
            repo,
            path="apps/api/src/__tests__/US-1.criteria.test.ts",
            skeleton=self.SKELETON,
        )
        prompt = prompt_for(self.SKELETON, context)

        assert context.bound == {"../app.ts": self.NAMES}
        assert "../app.ts" not in context.modules
        assert "Loaded afresh before every test" in prompt
        assert "  ../app.ts: app, booksRepository" in prompt
        # Every refused draft of Book Tracker's second fill typed a body `any`.
        assert "give it one of the exported types above, never `any`" in prompt
