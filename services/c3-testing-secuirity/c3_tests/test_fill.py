class TestTheLoop:
    async def test_a_refusal_travels_back_and_the_second_answer_is_taken(self) -> None:
        recorder = Recorder([_swap("expect(true).toBe(true);"), FILLED])

        outcome = await fill(_agent(recorder), skeleton=SKELETON, context=FillContext())

        assert outcome.accepted
        assert outcome.attempts == 2
        assert "holds for any program" in recorder.prompts[1]
        assert "Your previous answer was refused" in recorder.prompts[1]

    async def test_two_refusals_keep_the_skeleton(self) -> None:
        """Which generator authored a file has to stay a fact, so a fill that
        cannot satisfy the rule leaves the skeleton and says why."""
        recorder = Recorder([_swap("expect(true).toBe(true);"), _swap("const x = 1;")])

        outcome = await fill(_agent(recorder), skeleton=SKELETON, context=FillContext())

        assert not outcome.accepted
        assert outcome.content is None
        assert outcome.attempts == 2
        assert any("holds for any program" in reason for reason in outcome.refused_reasons)
        assert any("asserts nothing" in reason for reason in outcome.refused_reasons)

    async def test_the_first_prompt_carries_the_criteria_and_the_surface(self) -> None:
        recorder = Recorder([FILLED])
        context = FillContext(
            story_title="Place an order",
            criteria=["given a basket, when it is submitted, then an order exists"],
            modules={"../total": ["total", "discount"]},
            endpoints=["POST /orders creates an order"],
        )

        await fill(_agent(recorder), skeleton=SKELETON, context=context)

        first = recorder.prompts[0]
        assert "Place an order" in first
        assert "given a basket" in first
        assert "../total: total, discount" in first
        assert "POST /orders creates an order" in first
        assert "it.todo(" in first, "the file itself has to be in the prompt"

    async def test_nothing_leaks_into_the_first_prompt(self) -> None:
        """A refusal reason in the first prompt would mean the loop was primed
        with an answer nobody gave."""
        recorder = Recorder([FILLED])

        await fill(_agent(recorder), skeleton=SKELETON, context=FillContext())

        # The criterion text itself says "refused", so the check is for the
        # sentence the loop appends rather than for the word.
        assert "Your previous answer was refused" not in recorder.prompts[0]


