class TestATypeIsNotAConstructor:
    """TypeScript erases interfaces, so a test can construct one and only find
    out when it runs. The first live fill wrote
    `new CalculationHistory("1", "2 + 2 = 4")` against an
    `export interface CalculationHistory`, the collector imported the module
    without executing the body, the draft was accepted, and the failure arrived
    in the report looking like the application's fault.
    """

    SOURCES: ClassVar[dict[str, str]] = {
        "apps/api/src/models/Widget.ts": (
            "export interface Widget { id: string }\n"
            "export interface WidgetRepository { get(id: string): Widget }\n"
            "export class InMemoryWidgetRepository implements WidgetRepository {}\n"
        ),
    }

    SKELETON = '// story: US-1 A story\n// requirements: R-1\nit.todo("a widget is stored");\n'

    def _filled(self, statement: str) -> str:
        return (
            "// story: US-1 A story\n// requirements: R-1\n"
            'import { expect, it } from "vitest";\n'
            f'it("a widget is stored", async () => {{ {statement} }});\n'
        )

    def test_the_names_a_project_only_has_at_compile_time(self) -> None:
        assert type_only_names(self.SOURCES) == {"Widget", "WidgetRepository"}

    def test_constructing_one_is_refused_with_what_to_do_instead(self) -> None:
        problems = static_problems(
            self.SKELETON,
            self._filled('const w = new Widget("1"); expect(w.id).toBe("1");'),
            types_only={"Widget", "WidgetRepository"},
        )

        assert any("exports as a type rather than a class" in one for one in problems)
        assert any("plain object literal" in one for one in problems), (
            "a refusal the model cannot act on costs an attempt and teaches nothing"
        )

    def test_a_real_class_is_left_alone(self) -> None:
        problems = static_problems(
            self.SKELETON,
            self._filled("const r = new InMemoryWidgetRepository(); expect(r).toBeTruthy();"),
            types_only={"Widget", "WidgetRepository"},
        )

        assert problems == [], "InMemoryWidgetRepository is a class and exists at run time"

    def test_a_name_exported_as_both_is_allowed(self) -> None:
        """Refusing a legitimate `new` would send the model round a loop it
        cannot get out of, so the doubt goes the other way."""
        both = {
            "apps/api/src/Thing.ts": "export type Thing = { a: string }\nexport class Thing {}\n"
        }

        assert type_only_names(both) == set()

    def test_the_check_is_off_when_nothing_was_read(self) -> None:
        """No sources means no knowledge, and a rule with no input must not
        invent a refusal."""
        problems = static_problems(
            self.SKELETON, self._filled('const w = new Widget("1"); expect(w.id).toBe("1");')
        )

        assert problems == []


class TestRoutingAroundTheRule:
    """The model's answer to being blocked, observed live.

    Told it could not write `new CalculationHistory(...)`, the next draft wrote
    `new (await import("../models/CalculationHistory").then(m => m.CalculationHistory))(...)`,
    which constructs the same interface through an expression the first rule
    could not see. It is the component's own thesis appearing one stage early:
    a static check tells you what a model stopped writing, not what it stopped
    doing, which is why the repair guard runs mutants instead of reading code.
    """

    SKELETON = '// story: US-1 A story\n// requirements: R-1\nit.todo("a widget is stored");\n'

    def _filled(self, statement: str) -> str:
        return (
            "// story: US-1 A story\n// requirements: R-1\n"
            'import { expect, it } from "vitest";\n'
            f'it("a widget is stored", async () => {{ {statement} }});\n'
        )

    def test_constructing_through_an_expression_is_refused_too(self) -> None:
        problems = static_problems(
            self.SKELETON,
            self._filled(
                'const w = new (await import("../models/Widget").then(m => m.Widget))("1");'
                " expect(w).toBeTruthy();"
            ),
            types_only={"Widget"},
        )

        assert any("through an expression" in one for one in problems)

    def test_a_dynamic_import_in_a_body_is_refused_on_its_own(self) -> None:
        """Whatever it reaches for. The skeleton's imports are the whole of
        what a filled test may touch, and a body that imports reaches past
        them, which is how the rule above came to be needed."""
        problems = static_problems(
            self.SKELETON,
            self._filled('const m = await import("../models/Widget"); expect(m).toBeTruthy();'),
            types_only={"Widget"},
        )

        assert any("imports a module at run time" in one for one in problems)

    def test_an_ordinary_construction_still_passes(self) -> None:
        problems = static_problems(
            self.SKELETON,
            self._filled("const d = new Date(0); expect(d.getTime()).toBe(0);"),
            types_only={"Widget"},
        )

        assert problems == []


