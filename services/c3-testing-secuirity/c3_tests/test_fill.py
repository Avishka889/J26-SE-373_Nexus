"""The fence around what a model may write into a test file.

Every case here is a way an answer could look like a filled test and measure
nothing, and the fence exists because the incentive runs the wrong way: a pass
that is accepted when its tests pass teaches a model to write tests that cannot
fail, which is the behaviour this whole component exists to catch in others.

No model is called. The scripted answers are the cheats, written out, so the
guard is tested against the thing it guards against rather than against a
docstring.
"""

