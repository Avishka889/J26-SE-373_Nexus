def _story() -> UserStory:
    return UserStory(
        id="US-1",
        title="A story",
        epic="Fixture",
        points=3,
        priority="must",
        traces=["R-1"],
        acceptance=[
            AcceptanceCriterion(
                id="AC-1-1", given="a thing", when="it happens", then="it is observed"
            )
        ],
    )


SKELETON = """\
// Generated by the platform's testing component, one test per acceptance
// criterion.

// story: US-1 Place an order
// requirements: R-1
import { describe, it } from "vitest";

describe("Place an order", () => {
  it.todo("US-1 criterion 1: given a basket, when it is submitted, then an order exists");
  it.todo("US-1 criterion 2: given no items, when it is submitted, then it is refused");
});
"""

FILLED = """\
// Generated by the platform's testing component, one test per acceptance
// criterion.

// story: US-1 Place an order
// requirements: R-1
import { describe, expect, it } from "vitest";
import { total } from "../total";

describe("Place an order", () => {
  it("US-1 criterion 1: given a basket, when it is submitted, then an order exists", async () => {
    expect(total([{ price: 250, quantity: 2 }])).toBe(500);
  });
  it("US-1 criterion 2: given no items, when it is submitted, then it is refused", async () => {
    expect(total([])).toBe(0);
  });
});
"""


def _swap(body: str) -> str:
    """The good fill with its first assertion replaced."""
    return FILLED.replace("expect(total([{ price: 250, quantity: 2 }])).toBe(500);", body)


class Recorder:
    """Scripted answers, and every prompt kept for the assertions."""

    def __init__(self, answers: list[str]) -> None:
        self.answers = list(answers)
        self.prompts: list[str] = []

    def as_function(self) -> FunctionModel:
        def answer(messages, info):
            texts = [
                part.content
                for message in messages
                for part in getattr(message, "parts", [])
                if getattr(part, "part_kind", "") == "user-prompt"
            ]
            self.prompts.append(texts[-1] if texts else "")
            content = self.answers.pop(0)
            return ModelResponse(
                parts=[ToolCallPart(info.output_tools[0].name, json.dumps({"content": content}))]
            )

        return FunctionModel(answer)


def _agent(recorder: Recorder) -> Agent[None, FilledFile]:
    return build_filler(recorder.as_function())


