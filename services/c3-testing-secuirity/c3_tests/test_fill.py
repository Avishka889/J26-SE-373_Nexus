class TestWhatIsRefused:
    def test_a_test_that_vanished(self) -> None:
        """A report counts cases by name. A test that stops existing is a case
        that silently stops being reported, which is the quietest way for a
        suite to shrink."""
        dropped = FILLED.replace(
            '  it("US-1 criterion 2: given no items, when it is submitted, then it is refused", '
            "async () => {\n    expect(total([])).toBe(0);\n  });\n",
            "",
        )

        problems = static_problems(SKELETON, dropped)

        assert any(
            "was declared and is now neither written nor left as a todo" in p for p in problems
        )

    def test_a_test_that_was_renamed(self) -> None:
        renamed = FILLED.replace("criterion 1: given a basket", "criterion 1: a basket")

        problems = static_problems(SKELETON, renamed)

        assert any("neither written nor left as a todo" in p for p in problems)
        assert any("was not one of the declared names" in p for p in problems)

    @pytest.mark.parametrize(
        "body",
        [
            "expect(true).toBe(true);",
            "expect(true).toBeTruthy();",
            "expect(false).toBe(false);",
            "expect(1).toBe(1);",
            'expect("x").toBe("x");',
            "expect.assertions(0);",
        ],
    )
    def test_an_assertion_that_holds_for_any_program(self, body: str) -> None:
        """The cheapest way for a fill to look successful, and the one the
        literature has watched models take."""
        problems = static_problems(SKELETON, _swap(body))

        assert any("holds for any program" in p for p in problems)

    def test_a_body_that_asserts_nothing(self) -> None:
        problems = static_problems(SKELETON, _swap("const answer = total([]);"))

        assert any("asserts nothing, so it cannot fail" in p for p in problems)

    def test_only_which_would_disable_the_rest_of_the_file(self) -> None:
        problems = static_problems(SKELETON, FILLED.replace('  it("US-1', '  it.only("US-1', 1))

        assert any("disables every other test" in p for p in problems)

    @pytest.mark.parametrize(
        ("body", "expected"),
        [
            ("expect(Math.random()).toBeLessThan(1);", "unseeded randomness"),
            (
                "await new Promise(r => setTimeout(r, 10));\n    expect(total([])).toBe(0);",
                "a sleep",
            ),
            (
                "await fetch('http://example.com');\n    expect(total([])).toBe(0);",
                "and nothing else",
            ),
            ("expect(Date.now()).toBeGreaterThan(0);", "depend on when it runs"),
        ],
    )
    def test_a_body_that_cannot_be_repeated(self, body: str, expected: str) -> None:
        problems = static_problems(SKELETON, _swap(body))

        assert any(expected in p for p in problems)

    def test_a_dropped_header(self) -> None:
        """The header is what ties a test back to the story it exists for, and
        the report reads it."""
        problems = static_problems(SKELETON, FILLED.replace("// story: US-1 Place an order\n", ""))

        assert any("// story: US-1 Place an order" in p for p in problems)

    def test_an_answer_that_filled_nothing(self) -> None:
        """Leaving one criterion as a todo is a correct answer. Leaving all of
        them is the skeleton back again."""
        problems = static_problems(SKELETON, SKELETON)

        assert any("nothing was filled" in p for p in problems)


