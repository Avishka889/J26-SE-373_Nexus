"""One test per acceptance criterion, traced to the criterion it came from.

C1 wrote the acceptance criteria as given, when and then, and a criterion is
the unit a reader recognises: it is what the sprint says "done" means. So the
rules produce exactly one test per criterion, named after it, with a header
that says which story and which criterion it exists for.

**Named by the criterion's id and not by its position.** A test outlives the
design version it was written against, which is the whole premise of the healing
loop, and a position does not survive that: a criterion inserted ahead of another
moves what "criterion 1" means, so a preserved test would name a criterion it was
never written from. C1's criterion ids are carried across design versions and
never reissued, so the id is the reference that still means the same thing when
the test is read a version later.

**Why these are `it.todo` and not tests with bodies.** The rules know what the
criterion says and nothing about how to observe it: whether the total appears
in a component, in a response body, or in a repository is not written down
anywhere the rules can read. A body here would either be an assertion the rules
invented, or `expect(true).toBe(true)`, and a vacuously passing test is the
exact failure this component exists to prevent in others. `it.todo` is the
framework's own word for "declared and not written", it reports as a skip
rather than as a pass, and it is what the model fills in the next stage.

**Where each one goes.** A criterion belonging to a story that some endpoint
traces is an API test; anything else is a web test. That routing comes from the
platform's own traceability, which is a thing a general purpose test generator
pointed at the same repository does not have.

**Each test gets its own application.** A generated app keeps its data in a
store its `app.ts` builds when the module loads, so every test in a file that
imports it shares one store. A criterion's "given" then includes whatever the
tests before it left behind: Book Tracker's "given a user with one book already
in their list" found three books, not two, because the test before it had added
one, and the release it gated was refused in staging. So a skeleton on a side
whose `src/app.ts` exports something loads that module afresh before every test
and binds its exports under their own names, and a test sets up its own
"given".
"""

import json
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

from sdlc_contracts import ApiContract, SprintPlan, UserStory

from ..harness.report import case_id
from .api_tests import GeneratedCase

HEADER = (
    "// Generated by the platform's testing component, one test per acceptance\n"
    "// criterion. Each is declared and not yet written: `todo` reports as a\n"
    "// skip, never as a pass, so an unwritten test cannot be counted as one\n"
    "// that holds.\n"
)


#: The module a criteria test's side exports its application from, as the test
#: imports it. Every generated app has one, and the rules' own oracle imports it
#: the same way.
APP_MODULE = "../app.ts"

#: The first line of the setup, which is also how a file is recognised as
#: having one.
FRESH_APP_NOTE = (
    "// Each test starts from a freshly loaded application, and so from empty\n"
    '// stores: whatever a criterion\'s "given" needs, the test sets up itself.\n'
)

#: How a criteria test on the API side acts as the user does: through the app, in
#: process, as the contract tests reach it. Imported here rather than left to the
#: fill, as `expect` is: the model keeps a skeleton's imports and imports only the
#: modules it is told exist, so on Movie Tracker's live run (2026-10-06) no draft
#: could reach the API. One called a `request` nobody imported, others imported
#: one inside a body, and all six acceptance criteria stayed todos.
SUPERTEST_IMPORT = 'import request from "supertest";'

#: Where the setup binds its names, read back to learn which names they are.
SETUP_IMPORT = re.compile(
    r"\(\{\s*(?P<names>[^}]*)\}\s*=\s*await\s+import\(\s*\"(?P<from>[^\"]+)\"\s*\)\s*\)"
)


def fresh_app_block(names: Sequence[str], specifier: str = APP_MODULE) -> str:
    """The setup that loads `specifier` afresh before every test.

    `vi.resetModules` empties Vitest's module registry, so the dynamic import
    that follows evaluates the app again, with new stores; a static import is
    evaluated once per file, which is the sharing this replaces. The exports are
    bound under their own names, so a test written against a static import
    reads exactly as it did.
    """
    lets = "".join(f'let {name}: (typeof import("{specifier}"))["{name}"];\n' for name in names)
    return (
        FRESH_APP_NOTE
        + lets
        + "beforeEach(async () => {\n"
        + "  vi.resetModules();\n"
        + f'  ({{ {", ".join(names)} }} = await import("{specifier}"));\n'
        + "});\n"
    )


def fresh_app_of(source: str) -> tuple[str, list[str]] | None:
    """The module and names a file's setup binds, or None when it has no setup."""
    if FRESH_APP_NOTE not in source:
        return None
    match = SETUP_IMPORT.search(source)
    if match is None:
        return None
    names = [name.strip() for name in match.group("names").split(",") if name.strip()]
    return match.group("from"), names


@dataclass
class CriteriaSuite:
    files: dict[str, str] = field(default_factory=dict)
    cases: list[GeneratedCase] = field(default_factory=list)


def slug(value: str) -> str:
    """A story id as a filename, without inviting a path out of the directory."""
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "-", value).strip("-.")
    return cleaned or "story"


def endpoints_of(story: UserStory, contract: ApiContract) -> list[str]:
    """The endpoints the contract says serve this story.

    Carried into every case this file produces, and the reason is the classifier
    rather than the reader. Its two inputs are the requirement diff and the
    contract diff, and a criterion test used to carry no endpoint at all, so
    half its signal could never apply to the tests this component writes from a
    criterion. A criterion test broken by the API moving underneath it could
    only be read through whether its requirement happened to be reworded too.

    The same scan `side_for` already does to decide where the file goes. It was
    computing exactly this and throwing it away.
    """
    return [endpoint.id for endpoint in contract.endpoints if story.id in endpoint.traces.story_ids]


def side_for(story: UserStory, contract: ApiContract, apps: tuple[str, ...] = ()) -> str:
    """`api` when an endpoint traces this story, `web` otherwise.

    Constrained to apps the target actually has. A project with only a web app
    would otherwise get its API side criteria written to `apps/api`, where no
    runner is ever started and nothing would collect them: the tests would be
    in the repository, absent from every report, and nobody would be told. That
    is not hypothetical; it is what the first live run did.
    """
    side = "web"
    for endpoint in contract.endpoints:
        if story.id in endpoint.traces.story_ids:
            side = "api"
            break
    if not apps:
        return side
    if f"apps/{side}" in apps:
        return side
    # Whatever the target does have, preferring the first app a reader would
    # look in rather than silently writing where nothing runs.
    return apps[0].removeprefix("apps/") if apps[0].startswith("apps/") else side


def _title(story: UserStory, criterion: Any) -> str:
    """The name the runner reports, which is also half of the case id.

    The story id is here as well as the criterion id, although the criterion id
    already contains the story's number, because this string is what a reader
    greps in flat runner output and what a mutation finding names a test by.
    """
    return (
        f"{story.id} {criterion.id}: given {criterion.given}, "
        f"when {criterion.when}, then {criterion.then}"
    )


def build(
    sprint: SprintPlan,
    contract: ApiContract,
    apps: tuple[str, ...] = (),
    bound: Mapping[str, Sequence[str]] | None = None,
) -> CriteriaSuite:
    """A file per in scope story, a `todo` per criterion.

    In scope means proposed: the backlog is what a human has not committed to
    this sprint, and generating tests for it would put unwritten work in the
    report as though it were part of the increment.

    `bound` is, per side, what that side's `src/app.ts` exports. A side with
    names there gets the setup that loads the app afresh before every test.
    """
    suite = CriteriaSuite()
    for story in sprint.proposed:
        side = side_for(story, contract, apps)
        endpoints = endpoints_of(story, contract)
        path = f"apps/{side}/src/__tests__/{slug(story.id)}.criteria.test.ts"
        names = list((bound or {}).get(side, ()))
        lines = [
            HEADER,
            f"// story: {story.id} {story.title}",
            f"// requirements: {', '.join(story.traces) or 'none recorded'}",
        ]
        if names:
            # `expect` is imported here rather than left for the fill to add:
            # told to keep the setup exactly as it is, the model kept the import
            # line above it as well, and every draft of Book Tracker's second
            # fill was refused for calling `expect` without importing it.
            lines.append('import { beforeEach, describe, expect, it, vi } from "vitest";')
            if side == "api" and "app" in names:
                lines.append(SUPERTEST_IMPORT)
            lines.extend(["", fresh_app_block(names).rstrip("\n")])
        else:
            lines.append('import { describe, it } from "vitest";')
        lines.extend(["", f"describe({json.dumps(story.title)}, () => {{"])
        for criterion in story.acceptance:
            name = _title(story, criterion)
            lines.append(f"  it.todo({json.dumps(name)});")
            suite.cases.append(
                GeneratedCase(
                    suite_path=path,
                    id=case_id(path, story.title, name),
                    name=name,
                    # Not "integration": the test runs the app in process, on
                    # its in-memory store, and reaches no database (C3-12).
                    kind="acceptance" if side == "api" else "unit",
                    origin="skeleton",
                    story_id=story.id,
                    criterion_id=criterion.id,
                    requirement_ids=list(story.traces),
                    endpoint_ids=endpoints,
                )
            )
        lines.extend(["});", ""])
        suite.files[path] = "\n".join(lines)
    return suite
