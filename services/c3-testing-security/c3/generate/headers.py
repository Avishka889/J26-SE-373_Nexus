"""The opening comment of a criteria test file, kept true to what the file holds.

The rules write every acceptance criterion as an `it.todo`, and the file opens
by saying so (`criteria.HEADER`). The model then writes the tests and is told to
keep the header comments as they are, and it does: on the live clinic project
(2026-10-13) the files the project's repository received opened "Each is
declared and not yet written" over three written tests each. So the comment is
written again from the file once its tests are what they will be.
"""

import re

from .criteria import HEADER
from .fill import declared_names, written_names

#: The first line every criteria file this component writes opens with.
_OPENING = "// Generated by the platform's testing component, one test per acceptance\n"

#: The opening comment: the lines from the top that are comments, up to the
#: first that is not. The story and requirements lines come after a blank line.
_COMMENT = re.compile(r"\A(?://[^\n]*\n)+")


def header_for(written: int, declared: int) -> str:
    """The opening comment for a file with this many tests written and declared."""
    if written == 0:
        return HEADER
    if declared == 0:
        return _OPENING + "// criterion, each written from its criterion.\n"
    return (
        _OPENING
        + f"// criterion. {written} written; {declared} declared and not yet written:\n"
        + "// `todo` reports as a skip, never as a pass, so an unwritten test cannot\n"
        + "// be counted as one that holds.\n"
    )


def with_header(source: str) -> str:
    """`source` with its opening comment saying what it holds now.

    A file this component did not open is left as it is, and nothing after the
    opening comment changes.
    """
    if not source.startswith(_OPENING):
        return source
    comment = _COMMENT.match(source)
    if comment is None:
        return source
    header = header_for(len(written_names(source)), len(declared_names(source)))
    return header + source[comment.end() :]
