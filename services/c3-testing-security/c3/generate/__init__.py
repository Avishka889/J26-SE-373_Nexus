"""Test generation: what the rules can write, before any model is asked.

Two sources, and the split between them is not arbitrary. The acceptance
criteria say what "done" means and nothing about how to observe it, so the
rules can name a test and cannot write one. The API contract says exactly what
an operation answers, so the rules can write a test that runs. Everything a
model contributes is measured against this line: the skeleton arm is what the
rules produced, the filled arm is what the model added to it, and the yield is
the difference.

What comes out is a `Generation`: files to store, a manifest row per file, the
cases that now exist (all of them unrun, because they have not been run), and
the gaps no test can cover. The report the stage writes is built from those,
which is why the cases carry their traces rather than having them matched back
from a path afterwards.
"""

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field

from sdlc_contracts import ApiContract, ManifestRow, SprintPlan
from sdlc_contracts.openapi import to_openapi

from . import api_tests, criteria
from .api_tests import Gap, GeneratedCase

__all__ = ["Gap", "GeneratedCase", "Generation", "generate"]


@dataclass
class Generation:
    files: dict[str, str] = field(default_factory=dict)
    manifest: list[ManifestRow] = field(default_factory=list)
    cases: list[GeneratedCase] = field(default_factory=list)
    gaps: list[Gap] = field(default_factory=list)

    @property
    def summary(self) -> str:
        runnable = sum(1 for case in self.cases if case.kind == "api")
        declared = len(self.cases) - runnable
        parts = [f"{runnable} contract tests"]
        if declared:
            parts.append(f"{declared} acceptance criteria declared and not yet written")
        if self.gaps:
            parts.append(f"{len(self.gaps)} contract obligations nothing implements")
        return ", ".join(parts)


def generate(
    sprint: SprintPlan,
    contract: ApiContract,
    openapi: dict | None = None,
    *,
    apps: tuple[str, ...] = (),
    bound: Mapping[str, Sequence[str]] | None = None,
) -> Generation:
    """Everything the rules can write for one code version.

    `openapi` is the document the orchestrator exported, passed in rather than
    rebuilt so that the tests are generated from the same bytes a consumer of
    the API would read. It is rebuilt here only when a caller has none, which
    is the case in this package's own tests.

    `apps` is what the target actually has, so a criterion is never routed to a
    directory no runner is started in.

    `bound` is, per side, what that side's `src/app.ts` exports, which its
    criteria tests load afresh before every test (`criteria.fresh_app_block`).
    """
    document = openapi if openapi is not None else to_openapi(contract, title="the generated app")
    entities = {entity.name: entity for entity in contract.entities}
    request_schemas = {endpoint.id: endpoint.request for endpoint in contract.endpoints}

    api = api_tests.build(document, entities=entities, request_schemas=request_schemas)
    stories = criteria.build(sprint, contract, apps, bound)

    generation = Generation(
        files={**api.files, **stories.files},
        cases=[*api.cases, *stories.cases],
        gaps=list(api.gaps),
    )
    generation.manifest = [
        ManifestRow(
            path=path,
            stage="test-generation",
            arm="rule",
            generator="rule",
            # What this file is about, named by endpoint where the contract has
            # one and by story otherwise. A criteria test carries every endpoint
            # its story is served by, so the row lists them all rather than
            # picking one.
            implements=sorted(
                {
                    name
                    for case in generation.cases
                    if case.suite_path == path
                    for name in (case.endpoint_ids or [case.story_id or ""])
                }
                - {""}
            ),
            summary=_summary_for(path, generation),
        )
        for path in sorted(generation.files)
    ]
    return generation


def _summary_for(path: str, generation: Generation) -> str:
    cases = [case for case in generation.cases if case.suite_path == path]
    if path.endswith(".criteria.test.ts"):
        return f"{len(cases)} acceptance criteria, declared and not yet written."
    return f"{len(cases)} tests over what the contract declares."


#: The line every file this component writes begins with. Read back to decide
#: who wrote a suite, which is evidence in the file rather than a guess from
#: its name: a project is free to call a file `something.oracle.test.ts`.
SIGNATURE = "// Generated by the platform's testing component"


def origins_in(repo) -> dict[str, str]:
    """Which suites in this repository this component wrote, and as what.

    `skeleton` for what the rules wrote, `filled` for a criteria file whose
    tests have bodies. Everything else is absent from the map and therefore
    upstream, which is the honest default: not knowing who wrote a test is not
    the same as having written it.
    """
    found: dict[str, str] = {}
    for app in repo.apps:
        tests = repo.root / app / "src" / "__tests__"
        if not tests.is_dir():
            continue
        for path in sorted(tests.rglob("*.test.ts")):
            try:
                text = path.read_text(errors="replace")
            except OSError:
                continue
            if not text.startswith(SIGNATURE):
                continue
            relative = repo.relative(path)
            if path.name.endswith(".criteria.test.ts"):
                # A criteria file with bodies in it was filled; one still made
                # only of todos is what the rules left.
                found[relative] = "filled" if _has_written_test(text) else "skeleton"
            else:
                found[relative] = "skeleton"
    return found


def _has_written_test(text: str) -> bool:
    from .fill import written_names

    return bool(written_names(text))
