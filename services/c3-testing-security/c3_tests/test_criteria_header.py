"""A criteria file's opening comment says what is in the file now.

The rules write every acceptance criterion as an `it.todo`, and the file opens
by saying so. The model then writes the tests, it is told to keep the header
comments as they are, and it does: on the live clinic project (2026-10-13) the
files the project's repository received opened "Each is declared and not yet
written" over three written tests each.
"""

from c3.generate import SIGNATURE
from c3.generate.criteria import HEADER
from c3.generate.headers import with_header

STORY = "// story: US-2 As a receptionist, I can record a doctor\n// requirements: R-1, R-21\n"
TODO_A = '  it.todo("US-2 AC-2-1: given no doctor, when one is saved, then it is retrievable");\n'
TODO_B = '  it.todo("US-2 AC-2-2: given a doctor, when Saturday is chosen, then it is refused");\n'
WRITTEN_A = (
    '  it("US-2 AC-2-1: given no doctor, when one is saved, then it is retrievable", async () => {\n'
    "    expect(1).toBe(1);\n  });\n"
)
WRITTEN_B = (
    '  it("US-2 AC-2-2: given a doctor, when Saturday is chosen, then it is refused", async () => {\n'
    "    expect(2).toBe(2);\n  });\n"
)


def _file(*tests: str, header: str = HEADER) -> str:
    return f'{header}\n{STORY}\ndescribe("As a receptionist", () => {{\n{"".join(tests)}}});\n'


def _body(text: str) -> str:
    """Everything after the opening comment, which must not change."""
    return text.split("\n\n", 1)[1]


class TestTheOpeningComment:
    def test_a_file_of_todos_keeps_the_rules_header(self) -> None:
        source = _file(TODO_A, TODO_B)

        assert with_header(source) == source

    def test_a_file_whose_tests_are_all_written_says_so(self) -> None:
        said = with_header(_file(WRITTEN_A, WRITTEN_B))

        assert "declared and not yet written" not in said
        assert said.startswith(
            "// Generated by the platform's testing component, one test per acceptance\n"
            "// criterion, each written from its criterion.\n"
        )

    def test_a_file_with_some_still_declared_counts_both(self) -> None:
        said = with_header(_file(WRITTEN_A, TODO_B))

        assert "1 written; 1 declared and not yet written" in said
        assert "`todo` reports as a skip, never as a pass" in said

    def test_only_the_opening_comment_changes(self) -> None:
        source = _file(WRITTEN_A, TODO_B)

        assert _body(with_header(source)) == _body(source)

    def test_the_signature_that_says_who_wrote_the_file_is_kept(self) -> None:
        # `origins_in` reads it to tell this component's suites from upstream ones.
        assert with_header(_file(WRITTEN_A)).startswith(SIGNATURE)

    def test_a_header_written_before_is_brought_up_to_date(self) -> None:
        earlier = with_header(_file(WRITTEN_A, WRITTEN_B))
        # A test sent back to be written again is a todo once more.
        sent_back = earlier.replace(WRITTEN_B, TODO_B)

        said = with_header(sent_back)

        assert "1 written; 1 declared and not yet written" in said
        assert with_header(said) == said

    def test_a_file_this_component_did_not_open_is_left_alone(self) -> None:
        theirs = "// a project's own test\nimport { it } from 'vitest';\n" + WRITTEN_A

        assert with_header(theirs) == theirs
