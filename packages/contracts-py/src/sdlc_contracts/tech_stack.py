"""The tech stack proposal and selection. Chosen here, in C2, not in C1.

Scoring is arithmetic over counted facts derived from the design; the score is
not a field any model output type carries, so it cannot be invented. The
explanation prose is the only model written part and is validated against
invented figures exactly as C1's recommendation is.

A catalog entry without working generators says so with `available: false`
and a reason. A stack the platform cannot generate is shown honestly, never
generated by prose.
"""

from pydantic import Field, model_validator

from .wire import Prose, WireDatetime, WireModel


class CountedFact(WireModel):
    """One number the scoring rests on, named so a reader can check it."""

    label: str = Field(min_length=1)
    value: int = Field(ge=0)


class ScorePart(WireModel):
    label: str = Field(min_length=1)
    points: int


class StackLayer(WireModel):
    #: "frontend", "backend", "database": prose labels, not an enum, because a
    #: future stack may add a layer (a queue, a cache) without a schema change.
    name: str = Field(min_length=1)
    choice: str = Field(min_length=1)
    version: str = ""
    rationale: str = ""


class StackCandidate(WireModel):
    id: str = Field(min_length=1)
    name: str = Field(min_length=1)
    layers: list[StackLayer] = Field(min_length=1)
    #: Arithmetic over the counted facts. Not model fillable by construction.
    score: int = Field(ge=0, le=100)
    score_breakdown: list[ScorePart] = Field(default_factory=list)
    #: The guarded LLM explanation. Empty when the explainer failed; the stage
    #: still ships the arithmetic.
    explanation: Prose = ""
    #: Whether generators exist for this stack today. False is shown honestly.
    available: bool = True
    unavailable_reason: str | None = None

    @model_validator(mode="after")
    def unavailability_says_why(self) -> "StackCandidate":
        if not self.available and not self.unavailable_reason:
            raise ValueError(f"stack {self.id} is unavailable without saying why")
        if self.available and self.unavailable_reason:
            raise ValueError(f"stack {self.id} is available but carries a reason not to be")
        return self


class TechStackArtefact(WireModel):
    #: What the scoring read, so every number in an explanation is checkable.
    facts: list[CountedFact] = Field(default_factory=list)
    candidates: list[StackCandidate] = Field(min_length=1)
    recommended_id: str = Field(min_length=1)
    #: The human's selection, recorded with who and when. Defaults to the
    #: recommendation by the run and is changeable in the stage.
    selected_id: str | None = None
    selected_by: str | None = None
    selected_at: WireDatetime | None = None

    @model_validator(mode="after")
    def ids_resolve(self) -> "TechStackArtefact":
        known = {candidate.id for candidate in self.candidates}
        if self.recommended_id not in known:
            raise ValueError(f"recommended stack {self.recommended_id} is not a candidate")
        if self.selected_id is not None and self.selected_id not in known:
            raise ValueError(f"selected stack {self.selected_id} is not a candidate")
        return self
