"""Artefact contracts shared by the orchestrator and every component service.

Every artefact model is defined here once. The orchestrator and the component
services both depend on this package and neither declares a contract type of its
own, so the Semantic Architecture Graph cannot exist in two slightly different
shapes at the same time.

`contracts/*.schema.json` is generated from these models and committed. The
committed schema is the frozen artefact other components read and the TypeScript
types are generated from; CI fails when either drifts.
"""

